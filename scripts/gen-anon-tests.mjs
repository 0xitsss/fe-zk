// Generates src/tests/anon_vectors.fe from vectors/semaphore/lean_imt.json (which
// vectors/js/semaphore/group-vectors.mjs writes from @semaphore-protocol/group 4.14.5).
//   node scripts/gen-anon-tests.mjs && fe fmt
import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..")
const v = JSON.parse(fs.readFileSync(path.join(root, "vectors/semaphore/lean_imt.json"), "utf8"))

const first17 = v.roots_first_17
const depths = {}
for (const c of v.cases) depths[c.size] = c.depth
const last = v.cases.find((c) => c.size === 1024)
// depth of every size 1..17: ceil(log2(size)), checked against the reference cases
const depthOf = (n) => (n <= 1 ? 0 : Math.ceil(Math.log2(n)))
for (const [n, d] of Object.entries(depths)) if (depthOf(Number(n)) !== d) throw new Error(`depth ${n}`)

const arr = (xs) => `[\n${xs.map((x) => `        ${x},`).join("\n")}\n    ]`

const out = `//! GENERATED by scripts/gen-anon-tests.mjs from vectors/semaphore/lean_imt.json. Do not edit.
//! Source: ${v.tool}. Leaves: ${v.leaf_seed}.
use super::anon::{Anon, AnonMsg, deploy, insert, root_of}
use ingot::anon::hash_to_field
use ingot::field::Field
use std::evm::{Address, Evm}

fn leaf(_ i: u256) -> u256 {
    let l17 = ${arr(v.leaves)}
    if i < 17 {
        l17[i as usize]
    } else {
        i + 1
    }
}

fn roots17() -> [u256; 17] {
    ${arr(first17)}
}

/// Root after every one of the first 17 inserts (covers sizes 1..9, 16, 17 and every depth
/// 0..5), then the root of the 1024-leaf tree (depth 10). Reference: @semaphore-protocol/group.
#[test]
fn lean_imt_roots_match_semaphore_group() uses (evm: mut Evm) {
    let g = deploy()
    let r17 = roots17()
    var i: u256 = 0
    while i < 17 {
        assert(insert(g, leaf(i)) == r17[i as usize])
        assert(root_of(g) == r17[i as usize])
        i += 1
    }
    while i < 1024 {
        insert(g, leaf(i))
        i += 1
    }
    assert(root_of(g) == ${last.root})
    assert(depth_of(g) == ${last.depth})
}

#[test]
fn hash_to_field_matches_semaphore() {
${v.hash_to_field.map((h) => `    assert(hash_to_field(${h.input}).to_canonical() == ${h.output})`).join("\n")}
}
`.replace("use super::anon::{Anon, AnonMsg, deploy, insert, root_of}", "use super::anon::{deploy, depth_of, insert, root_of}")
  .replace("use std::evm::{Address, Evm}", "use std::evm::Evm")
fs.writeFileSync(path.join(root, "src/tests/anon_vectors.fe"), out)
console.log("wrote src/tests/anon_vectors.fe")
