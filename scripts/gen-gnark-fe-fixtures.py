#!/usr/bin/env python3
"""Emit src/tests/gnark_plonk_fixtures.fe (Fe constants) from vectors/gnark/<name>/fixture.json.

Pure transcription of what the Go generator (vectors/gnark/main.go, gnark v0.12.0) wrote, no
computation, except `log2(size)`. Run after scripts/regen-gnark-fixtures.sh.
Usage: python3 -I scripts/gen-gnark-fe-fixtures.py > src/tests/gnark_plonk_fixtures.fe
"""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FIX = [("gm", "mul"), ("gc", "mulcommit")]
h = lambda s: int(s, 16)


def pt(T, name, p):
    print(f"pub const {T}_{name}_X: u256 = {h(p[0])}")
    print(f"pub const {T}_{name}_Y: u256 = {h(p[1])}")


print("//! GENERATED by scripts/gen-gnark-fe-fixtures.py from vectors/gnark/*. Do not edit.")
print("//! gnark v0.12.0 PLONK keys, proofs, public inputs and replayed challenges. The KZG SRS is the")
print("//! real Perpetual Powers of Tau SRS (PSE ppot_0080_05, sha256 pinned in vectors/gnark/ptau.go).")
for tag, name in FIX:
    d = json.load(open(os.path.join(ROOT, "vectors", "gnark", name, "fixture.json")))
    T = tag.upper()
    nc = len(d["qcp"])
    size = d["size"]
    assert size & (size - 1) == 0
    print(f"\n// ---- {name}")
    print(f"pub const {T}_NP: usize = {d['nb_public']}")
    print(f"pub const {T}_NC: usize = {nc}")
    print(f"pub const {T}_POWER: u256 = {size.bit_length() - 1}")
    print(f"pub const {T}_W: u256 = {h(d['generator'])}")
    print(f"pub const {T}_SIZE_INV: u256 = {h(d['size_inv'])}")
    print(f"pub const {T}_K: u256 = {h(d['coset_shift'])}")
    for k in ["ql", "qr", "qm", "qo", "qk"]:
        pt(T, k.upper(), d[k])
    for i, s in enumerate(d["s"]):
        pt(T, f"S{i + 1}", s)
    for i, q in enumerate(d["qcp"]):
        pt(T, f"QCP{i}", q)
    print(f"pub fn {tag}_cci() -> [u256; {nc}] {{")
    print("    [" + ", ".join(str(x) for x in d["commit_constraint_ix"]) + "]")
    print("}")
    pt(T, "G1", d["g1"])
    for nm, v in zip(["G2_X0", "G2_X1", "G2_Y0", "G2_Y1"], d["g2"]):
        print(f"pub const {T}_{nm}: u256 = {h(v)}")
    for nm, v in zip(["X2_X0", "X2_X1", "X2_Y0", "X2_Y1"], d["g2_x"]):
        print(f"pub const {T}_{nm}: u256 = {h(v)}")
    words = [h(x) for x in d["proof_words"]]
    assert len(words) == 24 + 3 * nc
    print(f"pub fn {tag}_fixed() -> [u256; 24] {{")
    print("    [")
    for w in words[:24]:
        print(f"        {w},")
    print("    ]")
    print("}")
    print(f"pub fn {tag}_qcp_at_zeta() -> [u256; {nc}] {{")
    print("    [" + ", ".join(str(w) for w in words[24 : 24 + nc]) + "]")
    print("}")
    print(f"pub fn {tag}_bsb() -> [[u256; 2]; {nc}] {{")
    b = words[24 + nc :]
    print("    [" + ", ".join(f"[{b[2 * i]}, {b[2 * i + 1]}]" for i in range(nc)) + "]")
    print("}")
    print(f"pub fn {tag}_pubs() -> [u256; {len(d['public'])}] {{")
    print("    [" + ", ".join(str(h(x)) for x in d["public"]) + "]")
    print("}")
    c = d["challenges"]
    for k in ["gamma", "beta", "alpha", "zeta", "gamma_kzg", "random", "pi", "opening_lin", "folded_value"]:
        print(f"pub const {T}_CH_{k.upper()}: u256 = {h(c[k])}")
    for k in ["gamma_raw", "beta_raw", "alpha_raw", "zeta_raw"]:
        print(f"pub const {T}_CH_{k.upper()}: u256 = {h(c[k])}")
    if nc:
        print(f"pub const {T}_CH_HASHED_COMMIT: u256 = {h(c['hashed_commit'])}")
    pt(T, "CH_LIN", c["lin_digest"])
    pt(T, "CH_FOLDED", c["folded_digest"])
