# Reference values for the BLS12-381 / EIP-4844 tests in src/tests/ec_bls.fe, from py_ecc.
# Writes src/tests/ec_bls_vectors.fe:   python3 -I scripts/ec-vectors-bls.py > src/tests/ec_bls_vectors.fe
# (needs `pip install py_ecc`; tested with py_ecc 8.0.0). A 381-bit field element v is emitted
# as two u256 constants `<NAME>_HI = v >> 256` and `<NAME>_LO = v & (2^256 - 1)`.
import hashlib
from py_ecc.bls12_381 import G1, G2, add, multiply, neg, curve_order, field_modulus as p
from py_ecc.bls.hash_to_curve import map_to_curve_G2, clear_cofactor_G2
from py_ecc.optimized_bls12_381 import FQ2 as OFQ2, normalize

M = (1 << 256) - 1
def fp(name, v):
    v = int(v)
    print(f"pub const {name}_HI: u256 = {v >> 256}")
    print(f"pub const {name}_LO: u256 = {v & M}")
def pt1(name, py, P):
    print(f"// {name} = {py}")
    fp(name + "_X", P[0]); fp(name + "_Y", P[1])
def pt2(name, py, P):
    print(f"// {name} = {py}   (coordinates x.coeffs[0], x.coeffs[1], y.coeffs[0], y.coeffs[1])")
    fp(name + "_X0", P[0].coeffs[0]); fp(name + "_X1", P[0].coeffs[1])
    fp(name + "_Y0", P[1].coeffs[0]); fp(name + "_Y1", P[1].coeffs[1])

print("// GENERATED by scripts/ec-vectors-bls.py (py_ecc 8.0.0). Do not edit.")
fp("P", p)
s1 = 0x1234567890abcdef1234567890abcdef1234567890abcdef1234567890abcdef % curve_order
s2 = 0xfedcba0987654321fedcba0987654321fedcba0987654321fedcba0987654321 % curve_order
print(f"// s1 = 0x1234567890abcdef1234567890abcdef1234567890abcdef1234567890abcdef % curve_order")
print(f"pub const S1: u256 = {s1}")
print(f"// s2 = 0xfedcba0987654321fedcba0987654321fedcba0987654321fedcba0987654321 % curve_order")
print(f"pub const S2: u256 = {s2}")
pt1("G1", "G1", G1)
pt1("G1_2", "multiply(G1, 2)", multiply(G1, 2))
pt1("G1_3", "add(G1, multiply(G1, 2))", add(G1, multiply(G1, 2)))
pt1("G1_MSM", "add(multiply(G1, s1), multiply(multiply(G1, 2), s2))",
    add(multiply(G1, s1), multiply(multiply(G1, 2), s2)))
pt1("G1_NEG", "neg(G1)", neg(G1))
pt2("G2", "G2", G2)
pt2("G2_2", "multiply(G2, 2)", multiply(G2, 2))
pt2("G2_MSM", "add(multiply(G2, s1), multiply(multiply(G2, 2), s2))",
    add(multiply(G2, s1), multiply(multiply(G2, 2), s2)))
pt2("G2_NEG", "neg(G2)", neg(G2))
# MAP_FP2_TO_G2 (EIP-2537) = hash-to-curve map_to_curve (SSWU + 3-isogeny) then clear_cofactor
Q = normalize(clear_cofactor_G2(map_to_curve_G2(OFQ2([1, 2]))))
pt2("MAP_G2", "clear_cofactor_G2(map_to_curve_G2(FQ2([1, 2])))  # input u = 1 + 2u", Q)

