// Generates the transcript vector (vectors/transcript/transcript.json, Keccak via ethers) and
// src/tests/hash_vectors.fe: Fe tests with the expected values of every reference vector under
// vectors/poseidon, vectors/poseidon2 and vectors/transcript inlined.
// Run through scripts/regen-vectors.sh after the vector files exist.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { createRequire } from "module";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "vectors/js/package.json"));
const { ethers } = require("ethers");
const R = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;

const w = (x) => BigInt(x).toString(16).padStart(64, "0");
const keccak = (...words) => BigInt(ethers.utils.keccak256("0x" + words.map(w).join("")));

// ---- transcript reference (mirrors the layout documented in src/hash/transcript.fe)
const LABEL = 0x66657a6b2d746573742d76310n; // "fezk-test-v1"
const ops = [
  ["absorb", 11n],
  ["absorb", 22n],
  ["absorb_point", [33n, 44n]],
  ["squeeze", 0x616c706861n], // "alpha"
  ["absorb", R - 1n],
  ["squeeze", 0x62657461n], // "beta"
  ["squeeze", 0x62657461n], // same label again: counter must change the output
];
let state = keccak(1n, LABEL), counter = 0n;
const squeezed = [];
for (const [op, arg] of ops) {
  if (op === "absorb") state = keccak(2n, state, arg);
  else if (op === "absorb_point") {
    state = keccak(2n, state, arg[0]);
    state = keccak(2n, state, arg[1]);
  } else {
    const h = keccak(3n, state, arg, counter);
    state = h;
    counter += 1n;
    squeezed.push((h % R).toString());
  }
}
fs.mkdirSync(path.join(root, "vectors/transcript"), { recursive: true });
fs.writeFileSync(
  path.join(root, "vectors/transcript/transcript.json"),
  JSON.stringify(
    {
      source: `ethers ${ethers.version} keccak256 over big-endian 32-byte words, layout of src/hash/transcript.fe`,
      label: LABEL.toString(),
      ops: ops.map(([o, a]) => [o, Array.isArray(a) ? a.map(String) : a.toString()]),
      challenges: squeezed,
    },
    null,
    1,
  ) + "\n",
);

// ---- Fe tests
const rd = (f) => JSON.parse(fs.readFileSync(path.join(root, f), "utf8"));
const pos = rd("vectors/poseidon/poseidon.json");
const bn = rd("vectors/poseidon2/bn254_t3.json");
const kb = rd("vectors/poseidon2/koalabear_t16.json");

let t = `//! GENERATED by scripts/gen-hash-tests.js from the reference vectors under vectors/.
//! Do not edit. Sources: ${pos.source}; ${bn.source}; ${kb.source}; ethers keccak256.
use ingot::field::{Bn254Fr, Field, KoalaBear}
use ingot::hash::{
    Bn254Poseidon2, KoalaBearPoseidon2, Transcript, bn254_t3_permute, koalabear_t16_permute,
    merkle_root, poseidon_1, poseidon_2, poseidon_3, poseidon_4, poseidon_5,
}

fn fr(_ v: u256) -> Bn254Fr {
    match Bn254Fr::from_canonical(v) {
        Option::Some(x) => x,
        Option::None => {
            assert(false)
            Bn254Fr::zero()
        },
    }
}

fn kb(_ v: u256) -> KoalaBear {
    match KoalaBear::from_canonical(v) {
        Option::Some(x) => x,
        Option::None => {
            assert(false)
            KoalaBear::zero()
        },
    }
}

fn kb8(_ a: [u256; 8]) -> [KoalaBear; 8] {
    [kb(a[0]), kb(a[1]), kb(a[2]), kb(a[3]), kb(a[4]), kb(a[5]), kb(a[6]), kb(a[7])]
}

fn kb16(_ a: [u256; 16]) -> [KoalaBear; 16] {
    var out: [KoalaBear; 16] = [KoalaBear::zero(); 16]
    var i: usize = 0
    while i < 16 {
        out[i] = kb(a[i])
        i += 1
    }
    out
}

fn eq8(_ a: [KoalaBear; 8], _ b: [KoalaBear; 8]) -> bool {
    var i: usize = 0
    while i < 8 {
        if !a[i].eq(b[i]) {
            return false
        }
        i += 1
    }
    true
}

fn eq16(_ a: [KoalaBear; 16], _ b: [KoalaBear; 16]) -> bool {
    var i: usize = 0
    while i < 16 {
        if !a[i].eq(b[i]) {
            return false
        }
        i += 1
    }
    true
}

`;
const arr = (xs) => `[${xs.map((x) => BigInt(x).toString()).join(", ")}]`;
const names = ["", "poseidon_1", "poseidon_2", "poseidon_3", "poseidon_4", "poseidon_5"];

t += `#[test]\nfn poseidon_circomlib_vectors() {\n`;
for (const v of pos.vectors) {
  const args = v.inputs.map((x) => `fr(${x})`).join(", ");
  t += `    assert(${names[v.inputs.length]}(${args}).to_canonical() == ${v.output})\n`;
}
t += `}\n\n`;

t += `#[test]\nfn poseidon2_bn254_t3_reference_kat() {\n`;
for (const p of bn.permutation) {
  t += `    let o = bn254_t3_permute([${p.input.map((x) => `fr(${x})`).join(", ")}])\n`;
  p.output.forEach((x, i) => (t += `    assert(o[${i}].to_canonical() == ${x})\n`));
}
t += `}\n\n`;

t += `#[test]\nfn poseidon2_koalabear_t16_plonky3_kats() {\n`;
kb.permutation.forEach((p, n) => {
  t += `    let o${n} = koalabear_t16_permute(kb16(${arr(p.input)}))\n`;
  t += `    assert(eq16(o${n}, kb16(${arr(p.output)})))\n`;
});
t += `}\n\n`;

const m = kb.merkle;
t += `#[test]\nfn merkle_koalabear_plonky3_tree() {\n`;
t += `    let leaf = kb8(${arr(m.leaf)})\n`;
t += `    let path = [${m.path.map((p) => `kb8(${arr(p)})`).join(", ")}]\n`;
t += `    let root = kb8(${arr(m.root)})\n`;
t += `    let r = merkle_root<KoalaBearPoseidon2, [KoalaBear; 8], 3>(leaf, ${m.leaf_index}, path)\n`;
t += `    assert(r.is_some())\n    assert(eq8(r.unwrap(), root))\n`;
t += `    // wrong index (bit flipped), wrong leaf, and an index beyond the tree depth\n`;
t += `    assert(!eq8(merkle_root<KoalaBearPoseidon2, [KoalaBear; 8], 3>(leaf, ${m.leaf_index ^ 1}, path).unwrap(), root))\n`;
t += `    var bad = leaf\n    bad[0] = kb(5)\n`;
t += `    assert(!eq8(merkle_root<KoalaBearPoseidon2, [KoalaBear; 8], 3>(bad, ${m.leaf_index}, path).unwrap(), root))\n`;
t += `    assert(merkle_root<KoalaBearPoseidon2, [KoalaBear; 8], 3>(leaf, 8 + ${m.leaf_index}, path).is_none())\n`;
t += `}\n\n`;

const tr = rd("vectors/transcript/transcript.json");
t += `#[test]\nfn transcript_matches_ethers_keccak_reference() {\n`;
t += `    var t = Transcript::new(${tr.label})\n`;
let ci = 0;
for (const [op, a] of tr.ops) {
  if (op === "absorb") t += `    t.absorb(${a})\n`;
  else if (op === "absorb_point") t += `    t.absorb_point(${a[0]}, ${a[1]})\n`;
  else t += `    assert(t.squeeze(${a}).to_canonical() == ${tr.challenges[ci++]})\n`;
}
t += `}\n`;
fs.writeFileSync(path.join(root, "src/tests/hash_vectors.fe"), t);
console.log("hash tests written");
