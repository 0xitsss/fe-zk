#!/usr/bin/env python3
"""Generate semaphore/src/tests.fe from vectors/semaphore/depths.json (one real proof per depth,
made by @semaphore-protocol/proof, see vectors/js/semaphore/prove-examples.mjs) and the real
ceremony fixture vectors/groth16/real_semaphore_d10 (made by snarkjs on the ceremony zkey).
Run from anywhere: python3 scripts/gen-semaphore-tests.py"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
depths = json.loads((ROOT / "vectors/semaphore/depths.json").read_text())
real = ROOT / "vectors/groth16/real_semaphore_d10"
proof = json.loads((real / "proof.json").read_text())
pub = json.loads((real / "public.json").read_text())
inputs = json.loads((real / "inputs.json").read_text())

# snarkjs JSON proof -> Semaphore packed points: [a0, a1, b[0][1], b[0][0], b[1][1], b[1][0], c0, c1]
rp = [
    proof["pi_a"][0], proof["pi_a"][1],
    proof["pi_b"][0][1], proof["pi_b"][0][0], proof["pi_b"][1][1], proof["pi_b"][1][0],
    proof["pi_c"][0], proof["pi_c"][1],
]


def arr(p):
    return "[" + ", ".join(str(int(x)) for x in p) + "]"


o = []
w = o.append
w("//! Semaphore v4 verifier tests: real proofs from the official SDK (one per depth 1..10) and the real")
w("//! ceremony fixture. GENERATED by scripts/gen-semaphore-tests.py -- do not edit.")
w("//! Gas: `fe test --show-logs` prints the `GasUsed` events (what = depth).")
w("use ingot::{LOW_MAX_DEPTH, MAX_DEPTH, key_digest, verify_proof, verify_proof_high, verify_proof_low}")
w("use fe_zk::anon::hash_to_field")
w("use fe_zk::Field")
w("use std::evm::{Call, Ctx, Evm}")
w("")
w("const R: u256 = 21888242871839275222246405745257275088548364400416034343698204186575808495617")
w("")
w("#[event]")
w("struct GasUsed { what: u256, gas: u256 }")
w("")
w("// Proof of the real ceremony fixture (vectors/groth16/real_semaphore_d10, snarkjs), message 1, scope 42")
w("fn real_points() -> [u256; 8] {")
w(f"    {arr(rp)}")
w("}")
w("")
w("fn real_root() -> u256 {")
w(f"    {pub[0]}")
w("}")
w("")
w("fn real_nullifier() -> u256 {")
w(f"    {pub[1]}")
w("}")
w("")
w("#[test]")
w("fn real_d10_proof_accepted() uses (call: Call, ctx: Ctx) {")
w(f"    // the public inputs of the fixture are the hashes of message {inputs['message']} and scope {inputs['scope']}")
w(f"    assert(hash_to_field({inputs['message']}).to_canonical() == {pub[2]})")
w(f"    assert(hash_to_field({inputs['scope']}).to_canonical() == {pub[3]})")
w(f"    assert(verify_proof(10, real_root(), real_nullifier(), {inputs['message']}, {inputs['scope']}, real_points()))")
w("}")
w("")
w("#[test]")
w("fn real_d10_wrong_depth_and_signals_rejected() uses (call: Call, ctx: Ctx) {")
w(f"    assert(!verify_proof(9, real_root(), real_nullifier(), {inputs['message']}, {inputs['scope']}, real_points()))")
w(f"    assert(!verify_proof(10, real_root(), real_nullifier() + 1, {inputs['message']}, {inputs['scope']}, real_points()))")
w(f"    assert(!verify_proof(10, real_root(), real_nullifier(), 2, {inputs['scope']}, real_points()))")
w(f"    assert(!verify_proof(10, real_root(), real_nullifier(), {inputs['message']}, 43, real_points()))")
w("}")
w("")
for d in depths:
    n = d["depth"]
    w(f"fn d{n}_points() -> [u256; 8] {{")
    w(f"    {arr(d['points'])}")
    w("}")
    w("")
    w(f"fn d{n}_ok() -> bool uses (call: Call, ctx: Ctx) {{")
    w(f"    verify_proof({n}, {d['merkleTreeRoot']}, {d['nullifier']}, {d['message']}, {d['scope']}, d{n}_points())")
    w("}")
    w("")
    w("#[test]")
    w(f"fn depth_{n}_proof_accepted() uses (call: Call, ctx: Ctx, evm: mut Evm) {{")
    w("    let g0 = evm.gas()")
    w(f"    let ok = d{n}_ok()")
    w(f"    evm.emit(GasUsed {{ what: {n}, gas: g0 - evm.gas() }})")
    w("    assert(ok)")
    w("}")
    w("")
d1, d3, d4 = depths[0], depths[2], depths[3]


def call(d, depth=None, root=None, nul=None, msg=None, scope=None, pts=None):
    n = d["depth"]
    return "verify_proof({}, {}, {}, {}, {}, {})".format(
        depth if depth is not None else n,
        root if root is not None else d["merkleTreeRoot"],
        nul if nul is not None else d["nullifier"],
        msg if msg is not None else d["message"],
        scope if scope is not None else d["scope"],
        pts if pts is not None else f"d{n}_points()",
    )


w("#[test]")
w("fn depth_out_of_range_false() uses (call: Call, ctx: Ctx) {")
w("    // no revert, just false: depth 0, above MAX_DEPTH, and absurd values")
w("    assert(MAX_DEPTH == 10)")
for dep in ["0", "11", "12", "32", "33", "256", "0xffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffff"]:
    w(f"    assert(!{call(d1, depth=dep)})")
w("    assert(key_digest(0) == 0)")
w("    assert(key_digest(11) == 0)")
w("}")
w("")
w("#[test]")
w("fn depth_mismatch_false() uses (call: Call, ctx: Ctx) {")
w("    // a proof is only valid under the key of the depth it was made for")
for (d, wrong) in [(d1, [2, 3, 10]), (d3, [1, 2, 4, 10]), (d4, [3, 5, 9])]:
    for x in wrong:
        w(f"    assert(!{call(d, depth=x)})")
w("}")
w("")
w("#[test]")
w("fn key_digests_distinct_and_nonzero() {")
for a in range(1, 11):
    w(f"    assert(key_digest({a}) != 0)")
for a in range(1, 11):
    for b in range(a + 1, 11):
        w(f"    assert(key_digest({a}) != key_digest({b}))")
w("}")
w("")
w("#[test]")
w("fn tampered_message_false() uses (call: Call, ctx: Ctx) {")
w("    assert(d3_ok())")
w(f"    assert(!{call(d3, msg=int(d3['message']) + 1)})")
w(f"    assert(!{call(d3, msg=0)})")
w(f"    assert(!{call(d3, msg=d3['scope'])})")
w("}")
w("")
w("#[test]")
w("fn tampered_scope_false() uses (call: Call, ctx: Ctx) {")
w(f"    assert(!{call(d3, scope=int(d3['scope']) + 1)})")
w(f"    assert(!{call(d3, scope=0)})")
w("}")
w("")
w("#[test]")
w("fn tampered_nullifier_and_root_false() uses (call: Call, ctx: Ctx) {")
w(f"    assert(!{call(d3, nul=int(d3['nullifier']) + 1)})")
w(f"    assert(!{call(d3, root=int(d3['merkleTreeRoot']) + 1)})")
w(f"    assert(!{call(d3, nul=d3['merkleTreeRoot'], root=d3['nullifier'])})")
w("}")
w("")
w("#[test]")
w("fn non_canonical_words_false() uses (call: Call, ctx: Ctx) {")
w("    // root + r and nullifier + r are the same field element but not canonical: rejected, not reduced")
w(f"    assert(!{call(d3, root=f'{d3['merkleTreeRoot']} + R')})")
w(f"    assert(!{call(d3, nul=f'{d3['nullifier']} + R')})")
w(f"    assert(!{call(d3, root='R')})")
w(f"    assert(!{call(d3, nul='0xffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffff')})")
w("}")
w("")
w("#[test]")
w("fn tampered_points_false() uses (call: Call, ctx: Ctx) {")
w("    // every single word of the proof matters")
for i in range(8):
    w(f"    var p{i} = d3_points()")
    w(f"    p{i}[{i}] = p{i}[{i}] + 1")
    w(f"    assert(!{call(d3, pts=f'p{i}')})")
w("    // a word >= q is rejected, not reduced")
w("    var big = d3_points()")
w("    big[0] = 0xffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffff")
w(f"    assert(!{call(d3, pts='big')})")
w("    // all zero: the point at infinity is not a valid proof element")
w(f"    assert(!{call(d3, pts='[0, 0, 0, 0, 0, 0, 0, 0]')})")
w("}")
w("")
w("#[test]")
w("fn b_word_order_matters() uses (call: Call, ctx: Ctx) {")
w("    // SemaphoreVerifier.sol order is (imaginary, real); the snarkjs JSON order must be rejected")
w("    let p = d3_points()")
w("    assert(d3_ok())")
w("    let swapped: [u256; 8] = [p[0], p[1], p[3], p[2], p[5], p[4], p[6], p[7]]")
w(f"    assert(!{call(d3, pts='swapped')})")
w("    // A and C swapped")
w("    let ac: [u256; 8] = [p[6], p[7], p[2], p[3], p[4], p[5], p[0], p[1]]")
w(f"    assert(!{call(d3, pts='ac')})")
w("}")
w("")
w("#[test]")
w("fn proof_of_other_depth_with_depth_d_points_false() uses (call: Call, ctx: Ctx) {")
w("    // points of depth 4 against the signals of depth 3")
w(f"    assert(!{call(d3, pts='d4_points()')})")
w("}")

w("")
w("#[test]")
w("fn low_and_high_cover_disjoint_depths() uses (call: Call, ctx: Ctx) {")
w("    assert(LOW_MAX_DEPTH == 5)")
for d in depths:
    n = d["depth"]
    args = f"{n}, {d['merkleTreeRoot']}, {d['nullifier']}, {d['message']}, {d['scope']}, d{n}_points()"
    lo, hi = ("", "!") if n <= 5 else ("!", "")
    w(f"    assert({lo}verify_proof_low({args}))")
    w(f"    assert({hi}verify_proof_high({args}))")
w("}")
(ROOT / "semaphore/src/tests.fe").write_text("\n".join(o) + "\n")
print("wrote semaphore/src/tests.fe")
