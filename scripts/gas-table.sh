#!/usr/bin/env bash
# One reproducible gas table: fe-zk (Fe) vs the reference Solidity verifiers on the same proofs,
# executed as deployed contracts in revm; writes docs/GAS.md. See vectors/gas/ (gas-run, gas_table.py).
#
# Needs: fe (set FE to override), cargo, solc 0.8.24, python3. Optional: node + circomlibjs for the
# Poseidon reference row (NODE_MODULES_DIR, default vectors/js/node_modules, else `npm ci` is tried).
# Env: FE (fe binary), FE_OPT (fe -O level, default 1), GAS_WORK (scratch dir, default mktemp),
#      CARGO_TARGET_DIR (default $GAS_WORK/target), OUT (default docs/GAS.md), KEEP=1 keeps scratch.
# Dev box: PATH=/data/nightly-x86_64-unknown-linux-gnu/bin:$PATH CARGO_HOME=/data/cargo GAS_WORK=/data/tmp/gas-work
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
FE="${FE:-fe}"
FE_OPT="${FE_OPT:-1}"
OUT="${OUT:-$ROOT/docs/GAS.md}"
if [ -z "${GAS_WORK:-}" ]; then
  GAS_WORK="$(mktemp -d)"
  [ "${KEEP:-0}" = 1 ] || trap 'rm -rf "$GAS_WORK"' EXIT
fi
mkdir -p "$GAS_WORK"
export CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-$GAS_WORK/target}"
T0=$(date +%s)

echo "== 1. build gas-run (revm) and fe-zk-gen"
cargo build -q --release --manifest-path vectors/gas/Cargo.toml
cargo build -q --release --manifest-path gen/Cargo.toml -p fe-zk-gen
GAS_RUN="$CARGO_TARGET_DIR/release/gas-run"
GEN="$CARGO_TARGET_DIR/release/fe-zk-gen"

echo "== 2. fixtures for the Fe wrapper ingot (vectors/gas-fe)"
GF=vectors/gas-fe
cp src/tests/plonk_fixtures.fe "$GF/src/fx_plonk.fe"
cp src/tests/gnark_plonk_fixtures.fe "$GF/src/fx_gnark.fe"
python3 -I - <<'PY'
import json, re
d = json.load(open("vectors/kzg/fixtures/kzg.json"))
t = [int(x) for x in d["vk"]["tau_g2"]]
with open("vectors/gas-fe/src/fx_kzg.fe", "w") as f:
    f.write("// GENERATED by scripts/gas-table.sh from vectors/kzg/fixtures/kzg.json\n")
    for n, v in zip(["X0", "X1", "Y0", "Y1"], t):
        f.write(f"pub const TAU_{n}: u256 = {v}\n")
# G2 SRS points of the halo2 circuit, copied from the constants of the library module so the wrapper can use them
t = open("src/verifier/halo2/standard_plonk_lookup.fe").read()
src = ["SRS_G2_X0", "SRS_G2_X1", "SRS_G2_Y0", "SRS_G2_Y1", "SRS_S_G2_X0", "SRS_S_G2_X1", "SRS_S_G2_Y0", "SRS_S_G2_Y1"]
hx = [re.search(r"const " + n + r": u256 = (0x[0-9a-f]{64})", t).group(1) for n in src]
names = ["H_G2_X0", "H_G2_X1", "H_G2_Y0", "H_G2_Y1", "H_S_X0", "H_S_X1", "H_S_Y0", "H_S_Y1"]
with open("vectors/gas-fe/src/fx_halo2.fe", "w") as f:
    f.write("// GENERATED by scripts/gas-table.sh from the SRS_* constants in src/verifier/halo2/standard_plonk_lookup.fe\n")
    for n, v in zip(names, hx):
        f.write(f"pub const {n}: u256 = {v}\n")
PY

echo "== 3. fe-zk-gen: Groth16 verifiers from the snarkjs keys"
rm -rf "$GF/generated"
for fx in multiplier multiplier2 membership life_64 life_512; do
  name="G16$(echo "$fx" | sed 's/_//g;s/^./\U&/')"
  V=vectors/groth16/$fx
  "$GEN" groth16 --snarkjs "$V/verification_key.json" --proof "$V/proof.json" --public "$V/public.json" \
    --name "$name" --out "$GF/generated/$fx" --fe-zk-path ../../../.. >/dev/null
done

echo "== 4. fe build -O $FE_OPT (wrappers, generated verifiers, Life)"
rm -rf "$GAS_WORK/fe" "$GAS_WORK/g16" "$GAS_WORK/life" "$GAS_WORK/fri"
pids=()
"$FE" build "$GF" -O "$FE_OPT" --out-dir "$GAS_WORK/fe" >/dev/null & pids+=($!)
"$FE" build examples/life -O "$FE_OPT" --out-dir "$GAS_WORK/life" >/dev/null & pids+=($!)
"$FE" build examples/fri_stark -O "$FE_OPT" --out-dir "$GAS_WORK/fri" >/dev/null & pids+=($!)
for fx in multiplier multiplier2 membership life_64 life_512; do
  "$FE" build "$GF/generated/$fx" -O "$FE_OPT" --out-dir "$GAS_WORK/g16/$fx" >/dev/null & pids+=($!)
done
for p in "${pids[@]}"; do wait "$p" || { echo "fe build failed" >&2; exit 1; }; done

echo "== 5. circomlibjs Poseidon reference (optional)"
POS=""
NM="${NODE_MODULES_DIR:-$ROOT/vectors/js/node_modules}"
if [ ! -d "$NM/circomlibjs" ] && command -v npm >/dev/null 2>&1; then
  mkdir -p "$GAS_WORK/js"
  cp vectors/js/package.json vectors/js/package-lock.json "$GAS_WORK/js/"
  (cd "$GAS_WORK/js" && npm ci --silent >/dev/null 2>&1) && NM="$GAS_WORK/js/node_modules" || true
fi
if [ -d "$NM/circomlibjs" ] && command -v node >/dev/null 2>&1; then
  mkdir -p "$GAS_WORK/poseidon"
  for n in 2 3; do
    NODE_MODULES_DIR="$NM" node vectors/gas/poseidon_code.mjs "$n" > "$GAS_WORK/poseidon/poseidon_$n.bin"
  done
  POS="$GAS_WORK/poseidon"
  CLJ="$(python3 -I -c "import json,sys;print(json.load(open(sys.argv[1]))['version'])" "$NM/circomlibjs/package.json")"
else
  echo "   skipped (no circomlibjs)"
  CLJ="not installed"
fi

echo "== 6. measure and render $OUT"
python3 -I - "$GAS_WORK/meta.json" "$("$FE" --version)" "$FE_OPT" "$(solc --version | tail -1)" \
  "$(git rev-parse --short=12 HEAD)" "$("$GEN" --version 2>/dev/null || echo fe-zk-gen)" "$CLJ" <<'PY'
import json, re, sys
out, fe, opt, solc, commit, gen, clj = sys.argv[1:8]
lock = open("vectors/gas/Cargo.lock").read()
revm = re.search(r'name = "revm"\nversion = "([^"]+)"', lock).group(1)
json.dump({"fe": fe, "fe_opt": opt, "solc": solc, "commit": commit, "gen": gen, "revm": revm,
           "circomlibjs": clj}, open(out, "w"))
PY
mkdir -p "$(dirname "$OUT")"
python3 -I vectors/gas/gas_table.py --work "$GAS_WORK" --gas-run "$GAS_RUN" --out "$OUT" \
  --meta "$GAS_WORK/meta.json" --poseidon-ref "$POS"
echo "wrote $OUT in $(( $(date +%s) - T0 )) s"
