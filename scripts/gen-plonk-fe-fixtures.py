#!/usr/bin/env python3
"""Emit src/tests/plonk_fixtures.fe (Fe constants) from vectors/plonk/<name>/*.json.

Pure transcription of the snarkjs files, no computation. Run after scripts/regen-plonk-fixtures.sh and `node vectors/js/plonk-challenges.mjs vectors/plonk/<name>` (reference challenges from the snarkjs JS verifier).
Usage: python3 -I scripts/gen-plonk-fe-fixtures.py > src/tests/plonk_fixtures.fe
"""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FIX = [("m2", "multiplier2"), ("mb", "membership")]


def pt(p):
    # snarkjs projective affine (x, y, 1); infinity is (0, 1, 0) -> Fe/EVM encoding (0, 0)
    return (0, 0) if p[2] == "0" else (int(p[0]), int(p[1]))


print("//! GENERATED by scripts/gen-plonk-fe-fixtures.py from vectors/plonk/*. Do not edit.")
print("//! snarkjs 0.7.6 `plonk` verification keys, proofs and public signals (test-only insecure setup).")
for tag, name in FIX:
    d = os.path.join(ROOT, "vectors", "plonk", name)
    vk = json.load(open(os.path.join(d, "verification_key.json")))
    pr = json.load(open(os.path.join(d, "proof.json")))
    pub = json.load(open(os.path.join(d, "public.json")))
    T = tag.upper()
    print(f"\n// ---- {name}")
    print(f"pub const {T}_NP: usize = {vk['nPublic']}")
    print(f"pub const {T}_POWER: u256 = {vk['power']}")
    print(f"pub const {T}_W: u256 = {vk['w']}")
    print(f"pub const {T}_K1: u256 = {vk['k1']}")
    print(f"pub const {T}_K2: u256 = {vk['k2']}")
    for k in ["Qm", "Ql", "Qr", "Qo", "Qc", "S1", "S2", "S3"]:
        x, y = pt(vk[k])
        print(f"pub const {T}_{k.upper()}_X: u256 = {x}")
        print(f"pub const {T}_{k.upper()}_Y: u256 = {y}")
    X2 = vk["X_2"]
    for nm, v in [("X0", X2[0][0]), ("X1", X2[0][1]), ("Y0", X2[1][0]), ("Y1", X2[1][1])]:
        print(f"pub const {T}_X2_{nm}: u256 = {v}")
    words = []
    for k in ["A", "B", "C", "Z", "T1", "T2", "T3", "Wxi", "Wxiw"]:
        words += list(pt(pr[k]))
    for k in ["eval_a", "eval_b", "eval_c", "eval_s1", "eval_s2", "eval_zw"]:
        words.append(int(pr[k]))
    assert len(words) == 24
    print(f"pub fn {tag}_proof() -> [u256; 24] {{")
    print("    [")
    for w in words:
        print(f"        {w},")
    print("    ]")
    print("}")
    ch = json.load(open(os.path.join(d, "challenges.json")))
    for k in ["beta", "gamma", "alpha", "xi", "v", "u", "r0"]:
        print(f"pub const {T}_CH_{k.upper()}: u256 = {int(ch[k], 16)}")
    print(f"pub const {T}_CH_PI: u256 = {int(ch['PI(xi)'], 16)}")
    print(f"pub fn {tag}_pubs() -> [u256; {len(pub)}] {{")
    print("    [" + ", ".join(str(int(x)) for x in pub) + "]")
    print("}")
