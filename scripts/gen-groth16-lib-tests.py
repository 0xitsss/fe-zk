#!/usr/bin/env python3
"""Regenerates src/tests/groth16.fe: library-level Groth16 tests over the committed fixtures in
vectors/groth16 (snarkjs: multiplier, multiplier2, membership; arkworks: arkworks_multiplier).
Only reformats reference-tool output (snarkjs JSON / arkworks hex) into Fe constants."""
import json, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
V = os.path.join(ROOT, "vectors", "groth16")


def sj_g1(p):
    return (int(p[0]), int(p[1])) if p[2] != "0" else (0, 0)


def sj_g2(p):
    return (int(p[0][0]), int(p[0][1]), int(p[1][0]), int(p[1][1]))


def ark_words(h, n):
    b = bytearray.fromhex(h)
    b[-1] &= 0x3F
    return [int.from_bytes(b[32 * i:32 * i + 32], "little") for i in range(n)]


def load(name, ark):
    d = os.path.join(V, name)
    pub = [int(x) for x in json.load(open(os.path.join(d, "public.json")))]
    vk = json.load(open(os.path.join(d, "verification_key.json")))
    pr = json.load(open(os.path.join(d, "proof.json")))
    if not ark:
        return dict(
            alpha=sj_g1(vk["vk_alpha_1"]), beta=sj_g2(vk["vk_beta_2"]),
            gamma=sj_g2(vk["vk_gamma_2"]), delta=sj_g2(vk["vk_delta_2"]),
            ic=[sj_g1(p) for p in vk["IC"]], a=sj_g1(pr["pi_a"]),
            b=sj_g2(pr["pi_b"]), c=sj_g1(pr["pi_c"]), pub=pub)
    return dict(
        alpha=tuple(ark_words(vk["alpha_g1"], 2)), beta=tuple(ark_words(vk["beta_g2"], 4)),
        gamma=tuple(ark_words(vk["gamma_g2"], 4)), delta=tuple(ark_words(vk["delta_g2"], 4)),
        ic=[tuple(ark_words(h, 2)) for h in vk["gamma_abc_g1"]],
        a=tuple(ark_words(pr["a"], 2)), b=tuple(ark_words(pr["b"], 4)),
        c=tuple(ark_words(pr["c"], 2)), pub=pub)


FIX = [("multiplier", False), ("multiplier2", False), ("membership", False),
       ("arkworks_multiplier", True)]
data = {n: load(n, a) for n, a in FIX}

out = []
w = out.append
w("//! Groth16 verifier tests over real reference proofs (snarkjs and arkworks).")
w("//! GENERATED by scripts/gen-groth16-lib-tests.py from vectors/groth16 -- do not edit.")
w("//! Gas: `fe test --show-logs` prints the `GasUsed` events (what = number of public inputs).")
w("use ingot::ec::{G1, G2, G2Proof, pairing_check_proof}")
w("use ingot::field::{Bn254Fr, Field}")
w("use ingot::verifier::{Groth16Proof, Groth16Vk, groth16_verify as verify, groth16_verify_raw as verify_raw}")
w("use std::evm::{Call, Evm}")
w("")
w("const Q: u256 = 21888242871839275222246405745257275088696311157297823662689037894645226208583")
w("const R: u256 = 21888242871839275222246405745257275088548364400416034343698204186575808495617")
w("// On the twist, not in the order-r subgroup (scripts/ec-vectors.py)")
w("const BAD_X0: u256 = 2")
w("const BAD_X1: u256 = 1")
w("const BAD_Y0: u256 = 7292567877523311580221095596750716176434782432868683424513645834767876293070")
w("const BAD_Y1: u256 = 19659275751359636165940301690575149581329631496732780143538578556285923319774")
w("")
w("#[event]")
w("struct GasUsed { what: u256, gas: u256 }")
w("")


def g1(p):
    return f"G1::from_coords_or_infinity({p[0]}, {p[1]})"


def g2(p):
    return f"G2::from_coords_or_infinity({p[0]}, {p[1]}, {p[2]}, {p[3]})"


for n, _ in FIX:
    d = data[n]
    N = len(d["pub"])
    w(f"fn vk_{n}() -> Groth16Vk<{N}> {{")
    w("        Groth16Vk {")
    w(f"            alpha: {g1(d['alpha'])},")
    w(f"            beta: {g2(d['beta'])},")
    w(f"            gamma: {g2(d['gamma'])},")
    w(f"            delta: {g2(d['delta'])},")
    w(f"            ic0: {g1(d['ic'][0])},")
    w("            ic: [" + ", ".join(g1(p) for p in d["ic"][1:]) + "],")
    w("        }")
    w("}")
    w("")

w("""/// Every invalid case must be rejected; the valid one accepted. `oa/ob/oc` is a valid proof of a
/// different circuit.
fn battery<const N: usize>(
    _ vk: Groth16Vk<N>,
    _ a: [u256; 2],
    _ b: [[u256; 2]; 2],
    _ c: [u256; 2],
    _ x: [u256; N],
    _ oa: [u256; 2],
    _ ob: [[u256; 2]; 2],
    _ oc: [u256; 2],
) uses (call: Call)
{
    assert(verify_raw(vk, a, b, c, x))
    // tampered proof elements (other valid points)
    assert(!verify_raw(vk, [1, 2], b, c, x))
    assert(!verify_raw(vk, a, b, [1, 2], x))
    let gb: [[u256; 2]; 2] = [
        [
            10857046999023057135944570762232829481370756359578518086990519993285655852781,
            11559732032986387107991004021392285783925812861821192530917403151452391805634,
        ],
        [
            8495653923123431417604973247489272438418190587263600148770280649306958101930,
            4082367875863433681332203403145435568316851327593401208105741076214120093531,
        ],
    ]
    assert(!verify_raw(vk, a, gb, c, x))
    // A = -A, C = infinity
    assert(!verify_raw(vk, [a[0], Q - a[1]], b, c, x))
    assert(!verify_raw(vk, a, b, [0, 0], x))
    // tampered public input
    var t = x
    t[0] = x[0] + 1
    assert(!verify_raw(vk, a, b, c, t))
    // non-canonical public input: r and x + r (same residue mod r)
    var nc = x
    nc[0] = R
    assert(!verify_raw(vk, a, b, c, nc))
    nc[0] = x[0] + R
    assert(!verify_raw(vk, a, b, c, nc))
    // A, C, B not on curve; non-canonical coordinates
    assert(!verify_raw(vk, [a[0], a[1] + 1], b, c, x))
    assert(!verify_raw(vk, a, b, [c[0], c[1] + 1], x))
    assert(!verify_raw(vk, [a[0] + Q, a[1]], b, c, x))
    assert(!verify_raw(vk, a, [[b[0][0] + Q, b[0][1]], b[1]], c, x))
    assert(!verify_raw(vk, a, [[b[0][0] + 1, b[0][1]], b[1]], c, x))
    assert(!verify_raw(vk, a, [b[0], [b[1][0], b[1][1] + 1]], c, x))
    // B on the twist but outside the order-r subgroup: pairing precompile rejects
    assert(!verify_raw(vk, a, [[BAD_X0, BAD_X1], [BAD_Y0, BAD_Y1]], c, x))
    // B real/imag swapped
    assert(!verify_raw(vk, a, [[b[0][1], b[0][0]], [b[1][1], b[1][0]]], c, x))
    // proof of a different circuit
    assert(!verify_raw(vk, oa, ob, oc, x))
}

/// Swapped public inputs (only meaningful for N >= 2 with distinct inputs).
fn swapped<const N: usize>(
    _ vk: Groth16Vk<N>,
    _ a: [u256; 2],
    _ b: [[u256; 2]; 2],
    _ c: [u256; 2],
    _ x: [u256; N],
) uses (call: Call)
{
    var s = x
    s[0] = x[1]
    s[1] = x[0]
    assert(!verify_raw(vk, a, b, c, s))
}
""")


def arr2(p):
    return f"[{p[0]}, {p[1]}]"


def b2(p):
    return f"[[{p[0]}, {p[1]}], [{p[2]}, {p[3]}]]"


other = {"multiplier": "multiplier2", "multiplier2": "multiplier", "membership": "multiplier2",
         "arkworks_multiplier": "multiplier2"}
for n, _ in FIX:
    d = data[n]
    o = data[other[n]]
    N = len(d["pub"])
    xs = "[" + ", ".join(str(x) for x in d["pub"]) + "]"
    w("#[test]")
    w(f"fn groth16_{n}_battery() uses (call: Call) {{")
    w(f"    battery(vk_{n}(), {arr2(d['a'])}, {b2(d['b'])}, {arr2(d['c'])}, {xs}, {arr2(o['a'])}, {b2(o['b'])}, {arr2(o['c'])})")
    if N >= 2 and len(set(d["pub"][:2])) == 2:
        w(f"    swapped(vk_{n}(), {arr2(d['a'])}, {b2(d['b'])}, {arr2(d['c'])}, {xs})")
    w("}")
    w("")

# typed API + gas
d = data["membership"]
w("""#[test]
fn groth16_typed_api_and_gas() uses (evm: mut Evm, call: Call) {""")
for n, _ in FIX:
    d = data[n]
    N = len(d["pub"])
    fr = ", ".join(f"Bn254Fr::from_canonical({x}).unwrap()" for x in d["pub"])
    w(f"    let p_{n} = Groth16Proof {{")
    w(f"        a: G1::from_coords({d['a'][0]}, {d['a'][1]}).unwrap(),")
    w(f"        b: G2Proof::from_coords({d['b'][0]}, {d['b'][1]}, {d['b'][2]}, {d['b'][3]}).unwrap(),")
    w(f"        c: G1::from_coords({d['c'][0]}, {d['c'][1]}).unwrap(),")
    w("    }")
    w("    let g0 = evm.gas()")
    w(f"    let ok = verify(vk_{n}(), p_{n}, [{fr}])")
    w(f"    evm.emit(GasUsed {{ what: {N}, gas: g0 - evm.gas() }})")
    w("    assert(ok)")
w("}")
w("")
w("""/// A `G2Proof` accepts an on-curve non-subgroup point (the full `G2` check rejects it); the pairing
/// precompile then fails (EIP-197), which `pairing_try_proof` / `verify` map to `false`.
#[test]
fn proof_g2_non_subgroup_passes_cheap_check_then_pairing_rejects() uses (call: Call) {
    assert(G2Proof::from_coords(BAD_X0, BAD_X1, BAD_Y0, BAD_Y1).is_some())
    assert(G2::from_coords(BAD_X0, BAD_X1, BAD_Y0, BAD_Y1).is_none())
    let bad = G2Proof::from_coords(BAD_X0, BAD_X1, BAD_Y0, BAD_Y1).unwrap()
    let g = G1::generator()
    assert(!ingot::ec::pairing_try_proof([g], [bad]))
    // off-curve or non-canonical coordinates never become a G2Proof
    assert(G2Proof::from_coords(BAD_X0, BAD_X1, BAD_Y0 + 1, BAD_Y1).is_none())
    assert(G2Proof::from_coords(BAD_X0 + Q, BAD_X1, BAD_Y0, BAD_Y1).is_none())
    // infinity is explicit
    assert(G2Proof::from_coords(0, 0, 0, 0).is_some())
}

/// The validated-constants constructors agree with the checked ones on the real key points.
#[test]
fn vk_constants_pass_full_checks() {
    assert(G2::from_coords(""" + ", ".join(str(x) for x in data["membership"]["beta"]) + """).is_some())
    assert(G2::from_coords(""" + ", ".join(str(x) for x in data["membership"]["gamma"]) + """).is_some())
    assert(G2::from_coords(""" + ", ".join(str(x) for x in data["membership"]["delta"]) + """).is_some())
}
""")
