#!/usr/bin/env python3
"""Generate semaphore/src/lib.fe from the per-depth key modules (semaphore/src/keys_d<k>.fe, emitted by
fe-zk-gen via scripts/regen-semaphore-keys.sh).

Semaphore's ceremony keys share alpha, beta and gamma and differ in delta and the IC points per depth.
The generated dispatch builds each depth's key from the shared points (taken once, from depth 1) plus that
depth's delta and IC, and static_asserts that every depth module carries the same shared words. This keeps
a contract that dispatches all 10 depths under the 24,576-byte limit (the full per-depth key in code costs
about 400 bytes more per depth).
python3 scripts/gen-semaphore-lib.py"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
MAXD = 10
LOW_MAX = 5
SHARED = ["ALPHA_X", "ALPHA_Y"] + [f"{p}_{c}" for p in ("BETA", "GAMMA") for c in ("X0", "X1", "Y0", "Y1")]

o = []
w = o.append
w("//! GENERATED by scripts/gen-semaphore-lib.py from the key modules keys_d1..keys_d10 -- do not edit.")
w("//!")
w("//! Semaphore v4 proof verification for Fe contracts.")
w("//!")
w("//! `verify_proof` takes the fields of Semaphore's `SemaphoreProof` struct (what")
w("//! `@semaphore-protocol/proof` `generateProof` returns) and checks the Groth16 proof against the")
w("//! published per-depth verifying key of the Semaphore ceremony (depth 1..10, keys from")
w("//! `packages/proof/src/verification-keys.json`, see scripts/regen-semaphore-keys.sh).")
w("//!")
w("//! Public inputs, in the order of `SemaphoreVerifier.sol`:")
w("//! `[merkleTreeRoot, nullifier, hash(message), hash(scope)]` with `hash(x) = keccak256(x) >> 8`.")
w("//! `points` is the packed proof of Semaphore: `[a0, a1, b01, b00, b11, b10, c0, c1]`, i.e. B in")
w("//! EVM (imaginary, real) order exactly as passed to `SemaphoreVerifier.verifyProof`.")
w("use std::evm::{Call, Ctx}")
w("use fe_zk::groth16")
w("use fe_zk::anon::hash_to_field")
w("use fe_zk::{Field, G1, G2}")
for d in range(1, MAXD + 1):
    w(f"use ingot::keys_d{d}")
w("")
w("/// Largest Merkle tree depth this ingot has a key for (Semaphore ships keys up to 32; the")
w("/// examples only need the small ones, and each key costs compile time and code size).")
w(f"pub const MAX_DEPTH: u256 = {MAXD}")
w(f"/// Largest depth `verify_proof_low` handles.")
w(f"pub const LOW_MAX_DEPTH: u256 = {LOW_MAX}")
w("")
w("// alpha, beta, gamma are the same in every depth's key: checked at compile time, then taken from depth 1")
for d in range(2, MAXD + 1):
    for s in SHARED:
        w(f"static_assert(keys_d{d}::{s} == keys_d1::{s})")
w("const ALPHA: G1 = G1::from_coords_or_infinity(keys_d1::ALPHA_X, keys_d1::ALPHA_Y)")
for p in ("BETA", "GAMMA"):
    w(f"const {p}: G2 = G2::from_coords_or_infinity(keys_d1::{p}_X0, keys_d1::{p}_X1, keys_d1::{p}_Y0, keys_d1::{p}_Y1)")
w("")
w("/// Digest (`fe-zk-gen`, see the key module header) of the verifying key for `depth`, or 0 if there is no key.")
w("pub fn key_digest(_ depth: u256) -> u256 {")
for d in range(1, MAXD + 1):
    w(f"    if depth == {d} {{ return keys_d{d}::VK_DIGEST }}")
w("    0")
w("}")
w("")
for d in range(1, MAXD + 1):
    k = f"keys_d{d}"
    w(f"// depth {d}: delta and IC from the depth's key module (already validated by its static_asserts)")
    w(f"const D{d}_DELTA: G2 = G2::from_coords_or_infinity({k}::DELTA_X0, {k}::DELTA_X1, {k}::DELTA_Y0, {k}::DELTA_Y1)")
    for i in range(5):
        w(f"const D{d}_IC{i}: G1 = G1::from_coords_or_infinity({k}::IC{i}_X, {k}::IC{i}_Y)")
    w(f"fn vk_d{d}() -> groth16::Vk<4> {{")
    w(f"    groth16::Vk::from_consts(ALPHA, BETA, GAMMA, D{d}_DELTA, D{d}_IC0, [D{d}_IC1, D{d}_IC2, D{d}_IC3, D{d}_IC4])")
    w("}")
    w("")
w("""fn verify_with<const N: usize>(
    _ vk: groth16::Vk<N>,
    _ inputs: [u256; N],
    _ points: [u256; 8],
) -> bool
uses (call: Call, ctx: Ctx)
{
    groth16::verify_calldata(
        vk,
        [points[0], points[1]],
        [[points[3], points[2]], [points[5], points[4]]],
        [points[6], points[7]],
        inputs,
    )
}

fn signals(_ root: u256, _ nullifier: u256, _ message: u256, _ scope: u256) -> [u256; 4] {
    [
        root,
        nullifier,
        hash_to_field(message).to_canonical(),
        hash_to_field(scope).to_canonical(),
    ]
}
""")
for name, lo, hi, doc in [
    ("low", 1, LOW_MAX, "depth 1..LOW_MAX_DEPTH (groups up to 2^5 = 32 members)"),
    ("high", LOW_MAX + 1, MAXD, "depth LOW_MAX_DEPTH+1..MAX_DEPTH"),
]:
    w(f"/// Like `verify_proof`, but only for {doc}: false for any other depth.")
    w("/// Pulls only these keys into the contract, which keeps a contract that also holds a LeanImt under the")
    w("/// 24,576-byte limit (the tree alone is about 14 KB). Same checks, same result for a depth in range.")
    w(f"pub fn verify_proof_{name}(")
    w("    _ depth: u256,\n    _ root: u256,\n    _ nullifier: u256,\n    _ message: u256,\n    _ scope: u256,\n    _ points: [u256; 8],")
    w(") -> bool\nuses (call: Call, ctx: Ctx)\n{")
    w("    let inputs = signals(root, nullifier, message, scope)")
    for d in range(lo, hi + 1):
        w(f"    if depth == {d} {{ return verify_with(vk_d{d}(), inputs, points) }}")
    w("    false")
    w("}")
    w("")
w("""/// Verifies a Semaphore v4 proof. Returns false (never reverts) if `depth` is 0 or above
/// `MAX_DEPTH`, if any word is not canonical, or if the proof does not verify for that depth.
/// `message` and `scope` are the raw values; they are hashed like `Semaphore.sol` does.
/// The caller must still check that `root` is a root of its group and spend the nullifier.
/// Holds all ten keys (about 11 KB of code): see `verify_proof_low` for contracts that are near the
/// size limit.
pub fn verify_proof(
    _ depth: u256,
    _ root: u256,
    _ nullifier: u256,
    _ message: u256,
    _ scope: u256,
    _ points: [u256; 8],
) -> bool
uses (call: Call, ctx: Ctx)
{
    if depth <= LOW_MAX_DEPTH {
        return verify_proof_low(depth, root, nullifier, message, scope, points)
    }
    verify_proof_high(depth, root, nullifier, message, scope, points)
}""")
(ROOT / "semaphore/src/lib.fe").write_text("\n".join(o) + "\n")
print("wrote semaphore/src/lib.fe")
