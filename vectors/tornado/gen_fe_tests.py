#!/usr/bin/env python3
"""Emit examples/tornado/verifier/src/mainnet_tests.fe from vectors/tornado/proofs/*.json.

usage: python3 -I gen_fe_tests.py OUT.fe
The generated verifier's own tests.fe (fe-zk-gen) is left untouched; this adds the mainnet-proof tests.
"""
import glob
import json
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
proofs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(here, "proofs", "*.json")))]
assert len(proofs) >= 3


def arr(xs):
    return "[" + ", ".join(str(x) for x in xs) + "]"


def call(p, inputs=None):
    w = p["proof_words"]
    x = inputs if inputs is not None else p["public"]
    return "vp(c, %s, [%s, %s], %s, %s)" % (arr(w[0:2]), arr(w[2:4]), arr(w[4:6]), arr(w[6:8]), arr(x))


o = []
o.append("//! GENERATED by vectors/tornado/gen_fe_tests.py -- do not edit.")
o.append("//! Real `withdraw` proofs of the Tornado Cash classic 0.1 ETH pool, taken from Ethereum mainnet transactions")
o.append("//! (hashes in vectors/tornado/txs.txt). Verdicts must equal the deployed Verifier.sol's.")
o.append("use super::*")
o.append("use std::evm::{Address, Evm}")
o.append("")
o.append("fn deploy() -> Address uses (evm: mut Evm) {")
o.append("    evm.create2<TornadoVerifier>(value: Wei::zero(), args: (), salt: 0)")
o.append("}")
o.append("")
o.append("fn vp(_ p: Address, _ a: [u256; 2], _ b: [[u256; 2]; 2], _ c: [u256; 2], _ x: [u256; 6]) -> bool")
o.append("uses (evm: mut Evm)")
o.append("{")
o.append("    let r: bool = evm.call(")
o.append("        addr: p,")
o.append("        gas: 10000000,")
o.append("        value: Wei::zero(),")
o.append("        message: TornadoVerifierMsg::VerifyProof { a: a, b: b, c: c, input: x },")
o.append("    )")
o.append("    r")
o.append("}")
o.append("")
o.append("#[test]")
o.append("fn real_mainnet_withdraw_proofs_accepted() uses (evm: mut Evm) {")
o.append("    let c = deploy()")
for p in proofs:
    o.append("    // %s (block %d)" % (p["tx"], p["block"]))
    o.append("    assert(%s)" % call(p))
o.append("}")
o.append("")
# recipient swap: proof 0 with the recipient of proof 1 (and, separately, relayer / fee / refund mutations)
a, b = proofs[0], proofs[1]
assert a["public"][2] != b["public"][2]
swap = list(a["public"])
swap[2] = b["public"][2]
o.append("#[test]")
o.append("fn recipient_swap_rejected() uses (evm: mut Evm) {")
o.append("    let c = deploy()")
o.append("    // front-running attack: valid proof, attacker's recipient")
o.append("    assert(!%s)" % call(a, swap))
o.append("}")
o.append("")
rel = list(a["public"])
rel[3] = b["public"][3] if b["public"][3] != a["public"][3] else str((int(a["public"][3]) + 1))
fee = list(a["public"])
fee[4] = str(int(fee[4]) + 1)
o.append("#[test]")
o.append("fn relayer_and_fee_mutation_rejected() uses (evm: mut Evm) {")
o.append("    let c = deploy()")
o.append("    assert(!%s)" % call(a, rel))
o.append("    assert(!%s)" % call(a, fee))
o.append("}")
o.append("")
refund = list(a["public"])
refund[5] = str(int(refund[5]) + 1)
o.append("#[test]")
o.append("fn refund_mutation_rejected() uses (evm: mut Evm) {")
o.append("    let c = deploy()")
o.append("    assert(!%s)" % call(a, refund))
o.append("}")
o.append("")
open(sys.argv[1], "w").write("\n".join(o))
