#!/usr/bin/env python3
"""Turn <dir>/{proof,config,vectors}.json into a Fe test fixture and a per-configuration module.

Usage: emit_fe.py <dir> <fixture .fe> <config .fe> <name> [--vectors] [--min-bits N]

  fixture .fe   the flat proof words (`fib_proof()`), the public values and the Fiat-Shamir
                challenges printed by Plonky3 (`TR_*`); with --vectors also the extension-field and
                challenger vectors (only the small demo fixture carries them).
  config .fe    the per-configuration module: `PARAMS` (FriParams), `PROOF_WORDS`, `verify`.
                With --min-bits N it also asserts at compile time that the conjectured soundness
                (Plonky3's `log_blowup * num_queries + query_pow_bits`) is at least N.

Only data is converted; no value is computed here except the proof length, which is asserted
against the length of the emitted word list.
"""
import json
import sys


def hx(s):
    assert s.startswith("0x") and len(s) == 66
    return s


def arr(items):
    return "[" + ", ".join(items) + "]"


def ints(xs):
    return arr([str(x) for x in xs])


P = 0x7F000001
R_INV = pow(2**32, -1, P)


def mont(x):
    """serde_json of a Plonky3 KoalaBear is its Montgomery form (value * 2^32 mod p)."""
    assert 0 <= x < P
    return x * R_INV % P


def ext_list(xs):
    return arr([ints(x) for x in xs])


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    flags = sys.argv[1:]
    d, out, cfg_out, name = args[:4]
    with_vectors = "--vectors" in flags
    min_bits = None
    if "--min-bits" in flags:
        min_bits = int(flags[flags.index("--min-bits") + 1])
        args = [a for a in args if a != str(min_bits)]
        d, out, cfg_out, name = args[:4]
    proof = json.load(open(f"{d}/proof.json"))
    cfg = json.load(open(f"{d}/config.json"))
    vec = json.load(open(f"{d}/vectors.json"))
    log_n, log_b, log_f = cfg["log_trace_rows"], cfg["log_blowup"], cfg["log_final_poly_len"]
    nq = cfg["num_queries"]
    f = log_n - log_f
    lh = log_n + log_b

    ov = proof["opened_values"]
    op = proof["opening_proof"]
    assert proof["commitments"]["random"] is None
    assert ov["preprocessed_local"] is None and ov["preprocessed_next"] is None
    assert ov["random"] is None and len(ov["quotient_chunks"]) == 1
    assert proof["degree_bits"] == log_n
    assert len(op["commit_phase_commits"]) == f and len(op["query_proofs"]) == nq
    assert len(op["final_poly"]) == 1 << log_f
    assert len(op["commit_pow_witnesses"]) == f

    # ---- flat proof words, in the layout documented in src/verifier/fri.fe
    words = []

    def felts(xs):
        words.extend(str(mont(x)) for x in xs)

    def exts(xs):
        for e in xs:
            assert len(e) == 4
            felts(e)

    words.append(hx(proof["commitments"]["trace"]["value"]))
    words.append(hx(proof["commitments"]["quotient_chunks"]["value"]))
    exts(ov["trace_local"])
    exts(ov["trace_next"])
    exts(ov["quotient_chunks"][0])
    words.extend(hx(c["value"]) for c in op["commit_phase_commits"])
    felts(op["commit_pow_witnesses"])
    exts(op["final_poly"])
    felts([op["query_pow_witness"]])
    for q in op["query_proofs"]:
        ip = q["input_proof"]
        assert len(ip) == 2 and len(ip[0]["opened_values"]) == 1 and len(ip[1]["opened_values"]) == 1
        cpo = q["commit_phase_openings"]
        assert len(cpo) == f
        assert len(ip[0]["opened_values"][0]) == 2 and len(ip[1]["opened_values"][0]) == 4
        assert len(ip[0]["opening_proof"]) == lh and len(ip[1]["opening_proof"]) == lh
        felts(ip[0]["opened_values"][0])
        words.extend(hx(s) for s in ip[0]["opening_proof"])
        felts(ip[1]["opened_values"][0])
        words.extend(hx(s) for s in ip[1]["opening_proof"])
        exts([c["sibling_value"] for c in cpo])
        for j, c in enumerate(cpo):
            assert len(c["opening_proof"]) == lh - 1 - j
            words.extend(hx(s) for s in c["opening_proof"])

    # proof length from the layout formula (must equal src/verifier/fri.fe `proof_words`)
    fold_paths = f * (lh - 1) - f * (f - 1) // 2
    qw = 2 + lh + 4 + lh + 4 * f + fold_paths
    total = 34 + 2 * f + 4 * (1 << log_f) + 1 + nq * qw
    assert len(words) == total, (len(words), total)

    conj = cfg["soundness"]["conjectured_bits"]
    assert conj == log_b * nq + cfg["query_proof_of_work_bits"]
    if min_bits is not None:
        assert conj >= min_bits, f"conjectured {conj} < required {min_bits}"

    # ---- configuration module
    c = []
    w = c.append
    w(f"//! GENERATED by vectors/plonky3-stark/emit_fe.py from {d.rstrip('/')}/config.json. Do not edit.")
    w(f"//! FRI/STARK configuration `{name}`: trace 2^{log_n} rows, log_blowup {log_b}, final polynomial")
    w(f"//! 2^{log_f} coefficients, {nq} queries, commit PoW {cfg['commit_proof_of_work_bits']} bits, query PoW")
    w(f"//! {cfg['query_proof_of_work_bits']} bits. Conjectured soundness (Plonky3 `log_blowup * num_queries + query_pow_bits`):")
    w(f"//! {conj} bits; proven estimates in `docs/DESIGN.md`.")
    w("use core::ptr::MemArray")
    w("use ingot::verifier::fri::FriParams")
    w("use ingot::verifier::fri::verify as verify_with")
    w("")
    w("pub const PARAMS: FriParams = FriParams {")
    w(f"    log_n: {log_n},")
    w(f"    log_blowup: {log_b},")
    w(f"    log_final: {log_f},")
    w(f"    num_queries: {nq},")
    w(f"    commit_pow_bits: {cfg['commit_proof_of_work_bits']},")
    w(f"    query_pow_bits: {cfg['query_proof_of_work_bits']},")
    w("}")
    w(f"pub const PROOF_WORDS: usize = {total}")
    w("/// Plonky3 `FriParameters::conjectured_soundness_bits` of this configuration.")
    w(f"pub const CONJECTURED_BITS: u256 = {conj}")
    if min_bits is not None:
        w(f"static_assert(CONJECTURED_BITS >= {min_bits})")
    w("")
    w("/// `proof` is `PROOF_WORDS` words (`MemArray`, not `[u256; PROOF_WORDS]`: see `docs/DESIGN.md`).")
    w("pub fn verify(_ proof: MemArray<u256>, _ public: [u256; 3]) -> bool {")
    w("    verify_with(PARAMS, proof, public)")
    w("}")
    open(cfg_out, "w").write("\n".join(c) + "\n")

    # ---- fixture module
    o = []
    w = o.append
    w(f"//! GENERATED by vectors/plonky3-stark/emit_fe.py from {d.rstrip('/')}/*.json. Do not edit.")
    w("//! Plonky3 p3-uni-stark 0.4.2 Fibonacci proof (flat words), values printed by Plonky3.")
    w("use core::ptr::MemArray")
    w("")
    if with_vectors:
        keys = ["a", "b", "add", "sub", "mul", "sq", "inv", "pow_1000003"]
        cases = vec["ext"]["cases"]
        w(f"pub const EXT_CASES: [[[u256; 4]; 8]; {len(cases)}] = [")
        for cs in cases:
            w("    " + ext_list([cs[k] for k in keys]) + ",")
        w("]")
        w(f"pub const TWO_ADIC_GENERATORS: [u256; {len(vec['ext']['two_adic_generators'])}] = "
          + ints(vec["ext"]["two_adic_generators"]))
        w(f"pub const TWO_ADIC_GENERATOR_24: u256 = {vec['ext']['two_adic_generator_24']}")
        w(f"pub const GENERATOR: u256 = {vec['ext']['generator']}")
        w("")
        ch = vec["challenger"]
        ops = ch["ops"]
        assert [x["op"] for x in ops] == (
            ["observe_felts", "sample_ext", "observe_hash", "sample_bits"]
            + ["sample_ext"] * 6 + ["grind_check", "sample_ext"]
        ), "challenger script changed: update the Fe test"
        exts_out = [x for x in ch["outputs"] if isinstance(x, list)]
        bits = [x for x in ch["outputs"] if not isinstance(x, list)]
        assert len(bits) == 1
        w(f"pub const CHAL_FELTS: [u256; 4] = {ints(ops[0]['vals'])}")
        w(f"pub const CHAL_HASH: u256 = {hx(ops[2]['hash'])}")
        w(f"pub const CHAL_BITS: u256 = {bits[0]}")
        w(f"pub const CHAL_GRIND_BITS: u256 = {ops[10]['bits']}")
        w(f"pub const CHAL_WITNESS: u256 = {ops[10]['witness']}")
        w(f"pub const CHAL_EXT: [[u256; 4]; {len(exts_out)}] = {ext_list(exts_out)}")
        w("")

    tr = vec["transcript"]
    assert tr["pow_ok"]
    w(f"pub const TR_ALPHA: [u256; 4] = {ints(tr['alpha'])}")
    w(f"pub const TR_ZETA: [u256; 4] = {ints(tr['zeta'])}")
    w(f"pub const TR_FRI_ALPHA: [u256; 4] = {ints(tr['fri_alpha'])}")
    w(f"pub const TR_BETAS: [[u256; 4]; {f}] = {ext_list(tr['betas'])}")
    w(f"pub const TR_INDICES: [u256; {nq}] = {ints(tr['indices'])}")
    w("")
    w(f"pub const FIB_PUBLIC: [u256; 3] = {ints(cfg['public_values'])}")
    w(f"pub const FIB_PROOF_WORDS: usize = {total}")
    w("")
    w("/// The proof as a runtime-length memory array (what `verify` takes).")
    w("pub fn fib_proof() -> MemArray<u256> {")
    w(f"    let words: [u256; {total}] = [")
    for i in range(0, len(words), 4):
        w("        " + ", ".join(words[i:i + 4]) + ",")
    w("    ]")
    w(f"    var m = unsafe {{ MemArray<u256>::new_uninit({total}) }}")
    w("    var i: usize = 0")
    w(f"    while i < {total} {{")
    w("        m[i] = words[i]")
    w("        i += 1")
    w("    }")
    w("    m")
    w("}")
    open(out, "w").write("\n".join(o) + "\n")


main()
