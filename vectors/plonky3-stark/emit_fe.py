#!/usr/bin/env python3
"""Turn fib/{proof,config,vectors}.json into the Fe test fixture src/tests/fri_fixture.fe.

Usage: emit_fe.py <fib dir> <output .fe>
Only data is converted; no value is computed here.
"""
import json
import sys


def hx(s):
    assert s.startswith("0x") and len(s) == 66
    return s


def arr(items):
    return "[" + ", ".join(items) + "]"


def ints(xs):
    return arr([str(x) for x in xs])


P = 0x7F000001
R_INV = pow(2**32, -1, P)


def mont(x):
    """serde_json of a Plonky3 KoalaBear is its Montgomery form (value * 2^32 mod p)."""
    assert 0 <= x < P
    return x * R_INV % P


def mints(xs):
    return ints([mont(x) for x in xs])


def mext_list(xs):
    return arr([mints(x) for x in xs])


def ext_list(xs):
    return arr([ints(x) for x in xs])


def main():
    d, out = sys.argv[1], sys.argv[2]
    proof = json.load(open(f"{d}/proof.json"))
    cfg = json.load(open(f"{d}/config.json"))
    vec = json.load(open(f"{d}/vectors.json"))
    o = []
    w = o.append
    w("//! GENERATED by vectors/plonky3-stark/emit_fe.py from vectors/plonky3/fib/*.json. Do not edit.")
    w("//! Plonky3 p3-uni-stark 0.4.2 Fibonacci proof, test vectors printed by Plonky3.")
    w("use ingot::verifier::fri::{QueryProof, StarkProof}")
    w("")

    # ---- extension field vectors: [a, b, add, sub, mul, sq, inv, pow_1000003]
    keys = ["a", "b", "add", "sub", "mul", "sq", "inv", "pow_1000003"]
    cases = vec["ext"]["cases"]
    w(f"pub const EXT_CASES: [[[u256; 4]; 8]; {len(cases)}] = [")
    for c in cases:
        w("    " + ext_list([c[k] for k in keys]) + ",")
    w("]")
    w(f"pub const TWO_ADIC_GENERATORS: [u256; {len(vec['ext']['two_adic_generators'])}] = "
      + ints(vec["ext"]["two_adic_generators"]))
    w(f"pub const TWO_ADIC_GENERATOR_24: u256 = {vec['ext']['two_adic_generator_24']}")
    w(f"pub const GENERATOR: u256 = {vec['ext']['generator']}")
    w("")

    # ---- challenger script (ops replayed by hand in the test)
    ch = vec["challenger"]
    ops = ch["ops"]
    assert [x["op"] for x in ops] == (
        ["observe_felts", "sample_ext", "observe_hash", "sample_bits"]
        + ["sample_ext"] * 6 + ["grind_check", "sample_ext"]
    ), "challenger script changed: update the Fe test"
    exts = [x for x in ch["outputs"] if isinstance(x, list)]
    bits = [x for x in ch["outputs"] if not isinstance(x, list)]
    assert len(bits) == 1
    w(f"pub const CHAL_FELTS: [u256; 4] = {ints(ops[0]['vals'])}")
    w(f"pub const CHAL_HASH: u256 = {hx(ops[2]['hash'])}")
    w(f"pub const CHAL_BITS: u256 = {bits[0]}")
    w(f"pub const CHAL_GRIND_BITS: u256 = {ops[10]['bits']}")
    w(f"pub const CHAL_WITNESS: u256 = {ops[10]['witness']}")
    w(f"pub const CHAL_EXT: [[u256; 4]; {len(exts)}] = {ext_list(exts)}")
    w("")

    tr = vec["transcript"]
    assert tr["pow_ok"]
    w(f"pub const TR_ALPHA: [u256; 4] = {ints(tr['alpha'])}")
    w(f"pub const TR_ZETA: [u256; 4] = {ints(tr['zeta'])}")
    w(f"pub const TR_FRI_ALPHA: [u256; 4] = {ints(tr['fri_alpha'])}")
    w(f"pub const TR_BETAS: [[u256; 4]; 3] = {ext_list(tr['betas'])}")
    w(f"pub const TR_INDICES: [u256; 4] = {ints(tr['indices'])}")
    w("")

    # ---- the proof
    ov = proof["opened_values"]
    op = proof["opening_proof"]
    assert proof["commitments"]["random"] is None
    assert ov["preprocessed_local"] is None and ov["preprocessed_next"] is None
    assert ov["random"] is None and len(ov["quotient_chunks"]) == 1
    assert proof["degree_bits"] == cfg["log_trace_rows"]
    assert len(op["commit_phase_commits"]) == 3 and len(op["query_proofs"]) == cfg["num_queries"]
    w(f"pub const FIB_PUBLIC: [u256; 3] = {ints(cfg['public_values'])}")
    w("")
    w("pub fn fib_proof() -> StarkProof {")
    w("    StarkProof {")
    w(f"        trace_commit: {hx(proof['commitments']['trace']['value'])},")
    w(f"        quotient_commit: {hx(proof['commitments']['quotient_chunks']['value'])},")
    w(f"        trace_local: {mext_list(ov['trace_local'])},")
    w(f"        trace_next: {mext_list(ov['trace_next'])},")
    w(f"        quotient_chunk: {mext_list(ov['quotient_chunks'][0])},")
    w(f"        fri_commits: {arr([hx(c['value']) for c in op['commit_phase_commits']])},")
    w(f"        commit_pow_witnesses: {mints(op['commit_pow_witnesses'])},")
    w(f"        final_poly: {mext_list(op['final_poly'])},")
    w(f"        query_pow_witness: {mont(op['query_pow_witness'])},")
    w("        queries: [")
    for q in op["query_proofs"]:
        ip = q["input_proof"]
        assert len(ip) == 2 and len(ip[0]["opened_values"]) == 1 and len(ip[1]["opened_values"]) == 1
        cpo = q["commit_phase_openings"]
        w("            QueryProof {")
        w(f"                trace_row: {mints(ip[0]['opened_values'][0])},")
        w(f"                trace_path: {arr([hx(s) for s in ip[0]['opening_proof']])},")
        w(f"                quotient_row: {mints(ip[1]['opened_values'][0])},")
        w(f"                quotient_path: {arr([hx(s) for s in ip[1]['opening_proof']])},")
        w(f"                fold_sibling: {mext_list([c['sibling_value'] for c in cpo])},")
        flat = [hx(s) for c in cpo for s in c["opening_proof"]]
        w(f"                fold_paths: {arr(flat)},")
        w("            },")
    w("        ],")
    w("    }")
    w("}")
    open(out, "w").write("\n".join(o) + "\n")


main()
