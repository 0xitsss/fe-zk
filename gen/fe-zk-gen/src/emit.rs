//! Fe emitter. Turns a validated Groth16 verifying key into a self-contained Fe ingot:
//! `fe.toml`, `src/lib.fe` (the verifier contract) and optionally `src/tests.fe`.
//!
//! The emitted contract contains NO verification logic of its own: its only handler forwards the
//! calldata words to the library's `groth16_verify_raw`, where every safety check lives
//! (canonical inputs, curve membership, G2 handling, pairing result). There is no option to
//! switch checks off, and the emitter refuses keys that do not pass `Groth16Vk::validate`.

use crate::digest::key_digest;
use crate::model::{Groth16Proof, Groth16Vk, VkError};
use crate::TOOL_VERSION;
use num_bigint::BigUint;
use std::fmt::Write;

/// A valid proof plus its public inputs, used to emit the generated test.
#[derive(Clone, Debug)]
pub struct TestFixture {
    pub proof: Groth16Proof,
    pub public: Vec<BigUint>,
}

#[derive(Clone, Debug)]
pub struct EmitOptions {
    /// CamelCase name; the contract is `<name>Verifier`, the ingot `<lowercase name>_verifier`.
    pub name: String,
    /// File name of the key the code was generated from (header only).
    pub source: String,
    /// Path to the fe_zk ingot, relative to the emitted ingot directory.
    pub fe_zk_path: String,
    pub fixture: Option<TestFixture>,
}

impl Default for EmitOptions {
    fn default() -> Self {
        EmitOptions {
            name: "Groth16".into(),
            source: "verification_key.json".into(),
            fe_zk_path: "../..".into(),
            fixture: None,
        }
    }
}

#[derive(Clone, Debug)]
pub struct EmittedIngot {
    pub ingot_name: String,
    pub fe_toml: String,
    pub lib_fe: String,
    pub tests_fe: Option<String>,
}

fn bad(m: impl Into<String>) -> VkError {
    VkError::Parse(m.into())
}

fn check_name(name: &str) -> Result<(), VkError> {
    let mut c = name.chars();
    let ok = matches!(c.next(), Some(f) if f.is_ascii_alphabetic())
        && name.chars().all(|c| c.is_ascii_alphanumeric());
    if ok {
        Ok(())
    } else {
        Err(bad(format!(
            "--name must be alphanumeric starting with a letter, got '{name}'"
        )))
    }
}

/// Emit only the verifier module (`src/lib.fe`) with default options.
pub fn emit_fe(vk: &Groth16Vk) -> Result<String, VkError> {
    Ok(emit_ingot(vk, &EmitOptions::default())?.lib_fe)
}

/// Emit the full ingot. Validates the key first (via `key_digest`); any failure aborts.
pub fn emit_ingot(vk: &Groth16Vk, opts: &EmitOptions) -> Result<EmittedIngot, VkError> {
    check_name(&opts.name)?;
    let digest = key_digest(vk)?; // validates
    let n = vk.n_public;
    let ingot_name = format!("{}_verifier", opts.name.to_lowercase());
    let contract = format!("{}Verifier", opts.name);
    let msg = format!("{contract}Msg");

    let fe_toml = format!(
        "[ingot]\nname = \"{ingot_name}\"\nversion = \"0.1.0\"\n\n[dependencies]\nfe_zk = {{ path = \"{}\", allow_unsafe = true }}\n",
        opts.fe_zk_path
    );

    let mut s = String::new();
    let w = &mut s;
    writeln!(w, "//! GENERATED by fe-zk-gen {TOOL_VERSION} -- do not edit.").unwrap();
    writeln!(w, "//! Groth16 / BN254 verifier for {} public input(s).", n).unwrap();
    writeln!(w, "//! Source key : {}", opts.source).unwrap();
    writeln!(w, "//! Key digest : 0x{}", hex::encode(digest)).unwrap();
    writeln!(w, "//! (keccak256 over the canonical key encoding, see gen/README.md)").unwrap();
    writeln!(w, "//!").unwrap();
    writeln!(w, "//! The contract only forwards calldata to `groth16_verify_raw` in fe_zk, which does all").unwrap();
    writeln!(w, "//! checks: canonical inputs and coordinates, A/B/C on curve, pairing result == 1.").unwrap();
    writeln!(w, "//! ABI-compatible with snarkjs' Verifier.sol: `b` is in EVM order, i.e. each Fq2 element").unwrap();
    writeln!(w, "//! is `[imaginary, real]` = `[c1, c0]`, exactly what `snarkjs zkey export soliditycalldata`").unwrap();
    writeln!(w, "//! prints. Groth16 proofs are malleable: never use a proof or its hash as a nullifier.").unwrap();
    writeln!(w, "use fe_zk::ec::{{G1, G2}}").unwrap();
    writeln!(w, "use fe_zk::verifier::{{Groth16Vk, groth16_verify_raw}}").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "pub const N_PUBLIC: u256 = {n}").unwrap();
    writeln!(w, "pub const VK_DIGEST: u256 = 0x{}", hex::encode(digest)).unwrap();
    writeln!(w).unwrap();
    writeln!(w, "// Verifying key, validated by fe-zk-gen (canonical, on curve, in subgroup, non-degenerate).").unwrap();
    writeln!(w, "// G2 coordinates are (real, imaginary) parts: x0 + x1*u, y0 + y1*u.").unwrap();
    for (nm, p) in [("ALPHA", &vk.alpha_g1)] {
        writeln!(w, "pub const {nm}_X: u256 = {}", p.x).unwrap();
        writeln!(w, "pub const {nm}_Y: u256 = {}", p.y).unwrap();
    }
    for (nm, p) in [("BETA", &vk.beta_g2), ("GAMMA", &vk.gamma_g2), ("DELTA", &vk.delta_g2)] {
        writeln!(w, "pub const {nm}_X0: u256 = {}", p.x[0]).unwrap();
        writeln!(w, "pub const {nm}_X1: u256 = {}", p.x[1]).unwrap();
        writeln!(w, "pub const {nm}_Y0: u256 = {}", p.y[0]).unwrap();
        writeln!(w, "pub const {nm}_Y1: u256 = {}", p.y[1]).unwrap();
    }
    for (i, p) in vk.ic.iter().enumerate() {
        writeln!(w, "pub const IC{i}_X: u256 = {}", p.x).unwrap();
        writeln!(w, "pub const IC{i}_Y: u256 = {}", p.y).unwrap();
    }
    writeln!(w).unwrap();
    writeln!(w, "/// The verifying key as typed points. `from_validated_coords` is `unsafe` because it skips").unwrap();
    writeln!(w, "/// the checks: they were done once at generation time (and are re-done in the generated test).").unwrap();
    writeln!(w, "fn vk() -> Groth16Vk<{n}> {{").unwrap();
    writeln!(w, "    unsafe {{").unwrap();
    writeln!(w, "        Groth16Vk {{").unwrap();
    writeln!(w, "            alpha: G1::from_validated_coords(ALPHA_X, ALPHA_Y),").unwrap();
    for nm in ["beta", "gamma", "delta"] {
        let u = nm.to_uppercase();
        writeln!(
            w,
            "            {nm}: G2::from_validated_coords({u}_X0, {u}_X1, {u}_Y0, {u}_Y1),"
        )
        .unwrap();
    }
    writeln!(w, "            ic0: G1::from_validated_coords(IC0_X, IC0_Y),").unwrap();
    let ics: Vec<String> = (1..=n)
        .map(|i| format!("G1::from_validated_coords(IC{i}_X, IC{i}_Y)"))
        .collect();
    writeln!(w, "            ic: [{}],", ics.join(", ")).unwrap();
    writeln!(w, "        }}").unwrap();
    writeln!(w, "    }}").unwrap();
    writeln!(w, "}}").unwrap();
    writeln!(w).unwrap();
    let sig = format!("verifyProof(uint256[2],uint256[2][2],uint256[2],uint256[{n}])");
    writeln!(w, "msg {msg} {{").unwrap();
    writeln!(w, "    #[selector = sol(\"{sig}\")]").unwrap();
    writeln!(
        w,
        "    VerifyProof {{ a: [u256; 2], b: [[u256; 2]; 2], c: [u256; 2], input: [u256; {n}] }} -> bool,"
    )
    .unwrap();
    writeln!(w, "    #[selector = sol(\"vkDigest()\")]").unwrap();
    writeln!(w, "    VkDigest -> u256,").unwrap();
    writeln!(w, "}}").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "pub contract {contract} {{").unwrap();
    writeln!(w, "    recv {msg} {{").unwrap();
    writeln!(w, "        VerifyProof {{ a, b, c, input }} -> bool uses (call: Call) {{").unwrap();
    writeln!(w, "            // calldata b = [[x_imag, x_real], [y_imag, y_real]]; the library wants real first").unwrap();
    writeln!(w, "            let b_real_first: [[u256; 2]; 2] = [[b[0][1], b[0][0]], [b[1][1], b[1][0]]]").unwrap();
    writeln!(w, "            groth16_verify_raw(vk(), a, b_real_first, c, input)").unwrap();
    writeln!(w, "        }}").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "        VkDigest -> u256 {{").unwrap();
    writeln!(w, "            VK_DIGEST").unwrap();
    writeln!(w, "        }}").unwrap();
    writeln!(w, "    }}").unwrap();
    writeln!(w, "}}").unwrap();

    let tests_fe = match &opts.fixture {
        Some(f) => Some(emit_tests(vk, opts, f, &contract, &msg, &digest)?),
        None => None,
    };
    Ok(EmittedIngot {
        ingot_name,
        fe_toml,
        lib_fe: s,
        tests_fe,
    })
}

fn emit_tests(
    vk: &Groth16Vk,
    opts: &EmitOptions,
    f: &TestFixture,
    contract: &str,
    msg: &str,
    digest: &[u8; 32],
) -> Result<String, VkError> {
    let n = vk.n_public;
    if f.public.len() != n {
        return Err(bad(format!(
            "public.json has {} inputs, key expects {n}",
            f.public.len()
        )));
    }
    let p = &f.proof;
    let mut s = String::new();
    let w = &mut s;
    writeln!(w, "//! GENERATED by fe-zk-gen {TOOL_VERSION} -- do not edit.").unwrap();
    writeln!(w, "//! Key digest : 0x{}", hex::encode(digest)).unwrap();
    writeln!(w, "//! Fixture: one valid proof (from {}) and a battery of invalid ones;", opts.name).unwrap();
    writeln!(w, "//! every safety check of the library has a failing case. All calls go through the").unwrap();
    writeln!(w, "//! deployed contract. `b` is in calldata (EVM) order: [[x_imag, x_real], [y_imag, y_real]].").unwrap();
    writeln!(w, "use super::*").unwrap();
    writeln!(w, "use std::evm::{{Address, Evm}}").unwrap();
    writeln!(w, "use fe_zk::ec::{{G1, G2}}").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "const Q: u256 = 21888242871839275222246405745257275088696311157297823662689037894645226208583").unwrap();
    writeln!(w, "const R: u256 = 21888242871839275222246405745257275088548364400416034343698204186575808495617").unwrap();
    writeln!(w, "// On the twist but outside the order-r subgroup (py_ecc, scripts/ec-vectors.py)").unwrap();
    writeln!(w, "const BAD_X0: u256 = 2").unwrap();
    writeln!(w, "const BAD_X1: u256 = 1").unwrap();
    writeln!(w, "const BAD_Y0: u256 = 7292567877523311580221095596750716176434782432868683424513645834767876293070").unwrap();
    writeln!(w, "const BAD_Y1: u256 = 19659275751359636165940301690575149581329631496732780143538578556285923319774").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "#[event]").unwrap();
    writeln!(w, "struct GasUsed {{ what: u256, gas: u256 }}").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "const A0: u256 = {}", p.a.x).unwrap();
    writeln!(w, "const A1: u256 = {}", p.a.y).unwrap();
    writeln!(w, "const B_X_IMAG: u256 = {}", p.b.x[1]).unwrap();
    writeln!(w, "const B_X_REAL: u256 = {}", p.b.x[0]).unwrap();
    writeln!(w, "const B_Y_IMAG: u256 = {}", p.b.y[1]).unwrap();
    writeln!(w, "const B_Y_REAL: u256 = {}", p.b.y[0]).unwrap();
    writeln!(w, "const C0: u256 = {}", p.c.x).unwrap();
    writeln!(w, "const C1: u256 = {}", p.c.y).unwrap();
    writeln!(w).unwrap();
    let xs: Vec<String> = f.public.iter().map(|x| x.to_string()).collect();
    writeln!(w, "fn inputs() -> [u256; {n}] {{").unwrap();
    writeln!(w, "    [{}]", xs.join(", ")).unwrap();
    writeln!(w, "}}").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "fn deploy() -> Address uses (evm: mut Evm) {{").unwrap();
    writeln!(w, "    evm.create2<{contract}>(value: Wei::zero(), args: (), salt: 0)").unwrap();
    writeln!(w, "}}").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "fn vp(_ p: Address, _ a: [u256; 2], _ b: [[u256; 2]; 2], _ c: [u256; 2], _ x: [u256; {n}]) -> bool").unwrap();
    writeln!(w, "uses (evm: mut Evm)").unwrap();
    writeln!(w, "{{").unwrap();
    writeln!(w, "    let r: bool = evm").unwrap();
    writeln!(w, "        .call(addr: p, gas: 10000000, value: Wei::zero(), message: {msg}::VerifyProof {{ a: a, b: b, c: c, input: x }})").unwrap();
    writeln!(w, "    r").unwrap();
    writeln!(w, "}}").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "fn good_b() -> [[u256; 2]; 2] {{").unwrap();
    writeln!(w, "    [[B_X_IMAG, B_X_REAL], [B_Y_IMAG, B_Y_REAL]]").unwrap();
    writeln!(w, "}}").unwrap();
    writeln!(w).unwrap();

    let t = |w: &mut String, name: &str, body: &str| {
        writeln!(w, "#[test]").unwrap();
        writeln!(w, "fn {name}() uses (evm: mut Evm) {{").unwrap();
        writeln!(w, "    let p = deploy()").unwrap();
        for l in body.lines() {
            writeln!(w, "    {l}").unwrap();
        }
        writeln!(w, "}}").unwrap();
        writeln!(w).unwrap();
    };

    t(w, "valid_proof_accepted", &format!(
        "let g0 = evm.gas()\nlet ok = vp(p, [A0, A1], good_b(), [C0, C1], inputs())\nevm.emit(GasUsed {{ what: {n}, gas: g0 - evm.gas() }})\nassert(ok)"));
    t(w, "vk_digest_exposed", &format!(
        "let d: u256 = evm.call(addr: p, gas: 1000000, value: Wei::zero(), message: {msg}::VkDigest {{}})\nassert(d == VK_DIGEST)\nassert(d == 0x{})",
        hex::encode(digest)));
    t(w, "tampered_a_rejected",
        "assert(!vp(p, [1, 2], good_b(), [C0, C1], inputs()))\nassert(!vp(p, [A0, Q - A1], good_b(), [C0, C1], inputs()))");
    t(w, "tampered_b_rejected",
        "// the G2 generator is a valid point of the right group but the wrong proof element\nlet g = G2::generator()\nlet gb: [[u256; 2]; 2] = [[g.x1(), g.x0()], [g.y1(), g.y0()]]\nassert(!vp(p, [A0, A1], gb, [C0, C1], inputs()))");
    t(w, "tampered_c_rejected",
        "assert(!vp(p, [A0, A1], good_b(), [1, 2], inputs()))\nassert(!vp(p, [A0, A1], good_b(), [0, 0], inputs()))");
    t(w, "tampered_public_input_rejected",
        "var x = inputs()\nx[0] = x[0] + 1\nassert(!vp(p, [A0, A1], good_b(), [C0, C1], x))");
    t(w, "non_canonical_public_input_rejected",
        "// r itself and x + r (same residue mod r) must be rejected, never reduced\nvar x = inputs()\nx[0] = R\nassert(!vp(p, [A0, A1], good_b(), [C0, C1], x))\nvar y = inputs()\ny[0] = y[0] + R\nassert(!vp(p, [A0, A1], good_b(), [C0, C1], y))\nvar z = inputs()\nz[0] = 0xffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffff\nassert(!vp(p, [A0, A1], good_b(), [C0, C1], z))");
    t(w, "non_canonical_coordinate_rejected",
        "assert(!vp(p, [A0 + Q, A1], good_b(), [C0, C1], inputs()))\nassert(!vp(p, [A0, A1], good_b(), [C0 + Q, C1], inputs()))\nassert(!vp(p, [A0, A1], [[B_X_IMAG + Q, B_X_REAL], [B_Y_IMAG, B_Y_REAL]], [C0, C1], inputs()))");
    t(w, "point_not_on_curve_rejected",
        "assert(!vp(p, [A0, A1 + 1], good_b(), [C0, C1], inputs()))\nassert(!vp(p, [A0, A1], good_b(), [C0, C1 + 1], inputs()))\nassert(!vp(p, [A0, A1], [[B_X_IMAG, B_X_REAL], [B_Y_IMAG, B_Y_REAL + 1]], [C0, C1], inputs()))");
    t(w, "b_not_in_subgroup_rejected",
        "// on the twist curve, order not r: the pairing precompile (EIP-197) refuses it\nassert(!vp(p, [A0, A1], [[BAD_X1, BAD_X0], [BAD_Y1, BAD_Y0]], [C0, C1], inputs()))");
    t(w, "b_real_imag_swapped_rejected",
        "// snarkjs JSON order instead of EVM order\nassert(!vp(p, [A0, A1], [[B_X_REAL, B_X_IMAG], [B_Y_REAL, B_Y_IMAG]], [C0, C1], inputs()))");
    t(w, "a_and_c_swapped_rejected",
        "assert(!vp(p, [C0, C1], good_b(), [A0, A1], inputs()))");
    if n >= 2 && f.public[0] != f.public[1] {
        t(w, "swapped_public_inputs_rejected",
            "var x = inputs()\nlet t = x[0]\nx[0] = x[1]\nx[1] = t\nassert(!vp(p, [A0, A1], good_b(), [C0, C1], x))");
    }
    t(w, "all_zero_public_inputs_rejected",
        &format!("assert(!vp(p, [A0, A1], good_b(), [C0, C1], [{}]))", vec!["0"; n].join(", ")));

    writeln!(w, "/// The key constants pass the full checks of the library (canonical, on curve, G2 subgroup).").unwrap();
    writeln!(w, "#[test]").unwrap();
    writeln!(w, "fn vk_constants_pass_full_checks() {{").unwrap();
    writeln!(w, "    assert(G1::from_coords(ALPHA_X, ALPHA_Y).is_some())").unwrap();
    for u in ["BETA", "GAMMA", "DELTA"] {
        writeln!(
            w,
            "    assert(G2::from_coords({u}_X0, {u}_X1, {u}_Y0, {u}_Y1).is_some())"
        )
        .unwrap();
    }
    for i in 0..=n {
        writeln!(w, "    assert(G1::from_coords(IC{i}_X, IC{i}_Y).is_some())").unwrap();
    }
    writeln!(w, "}}").unwrap();
    Ok(s)
}
