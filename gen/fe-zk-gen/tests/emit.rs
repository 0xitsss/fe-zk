//! Emitter tests: determinism, snapshot stability, key digest in output, refusal of invalid keys,
//! and (ignored by default, needs `fe` on PATH) emitting into a temp dir and running `fe test`.
//! Run the slow ones with `cargo test -- --ignored`.

use fe_zk_gen::{
    emit_fe, emit_ingot, key_digest, parse_arkworks, parse_arkworks_proof, parse_public,
    parse_snarkjs, parse_snarkjs_proof, EmitOptions, Groth16Vk, TestFixture, G1, G2,
};
use std::path::PathBuf;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn read(rel: &str) -> String {
    let p = root().join("vectors/groth16").join(rel);
    std::fs::read_to_string(&p).unwrap_or_else(|e| panic!("{}: {e}", p.display()))
}

fn load(name: &str) -> (Groth16Vk, TestFixture) {
    let ark = name.starts_with("arkworks");
    let vkj = read(&format!("{name}/verification_key.json"));
    let pj = read(&format!("{name}/proof.json"));
    let (vk, proof) = if ark {
        (
            parse_arkworks(&vkj).unwrap(),
            parse_arkworks_proof(&pj).unwrap(),
        )
    } else {
        (
            parse_snarkjs(&vkj).unwrap(),
            parse_snarkjs_proof(&pj).unwrap(),
        )
    };
    let public = parse_public(&read(&format!("{name}/public.json"))).unwrap();
    (vk, TestFixture { proof, public })
}

const NAMES: [&str; 4] = [
    "multiplier",
    "multiplier2",
    "membership",
    "arkworks_multiplier",
];

fn opts(name: &str, fx: Option<TestFixture>) -> EmitOptions {
    EmitOptions {
        name: "Fixture".into(),
        source: format!("{name}/verification_key.json"),
        fe_zk_path: "../..".into(),
        fixture: fx,
    }
}

#[test]
fn emission_is_deterministic_and_carries_digest() {
    for n in NAMES {
        let (vk, fx) = load(n);
        let a = emit_ingot(&vk, &opts(n, Some(fx.clone()))).unwrap();
        let b = emit_ingot(&vk, &opts(n, Some(fx))).unwrap();
        assert_eq!(a.lib_fe, b.lib_fe, "{n}");
        assert_eq!(a.tests_fe, b.tests_fe, "{n}");
        assert_eq!(a.fe_toml, b.fe_toml, "{n}");
        let d = hex::encode(key_digest(&vk).unwrap());
        assert!(
            a.lib_fe
                .contains(&format!("pub const VK_DIGEST: u256 = 0x{d}")),
            "{n}"
        );
        assert!(a.lib_fe.contains(&format!("Key digest : 0x{d}")), "{n}");
        assert!(a.lib_fe.contains("GENERATED by fe-zk-gen"), "{n}");
        assert!(a.lib_fe.contains("do not edit"), "{n}");
        assert!(a.tests_fe.unwrap().contains(&d), "{n}");
        // all logic is forwarded to the library
        assert!(a
            .lib_fe
            .contains("groth16_verify_raw(vk(), a, b_real_first, c, input)"));
        assert!(a.fe_toml.contains("allow_unsafe = true"));
    }
}

#[test]
fn selector_signature_matches_snarkjs_solidity_verifier() {
    for (n, k) in [("multiplier", 1), ("multiplier2", 2), ("membership", 3)] {
        let (vk, _) = load(n);
        let sol = read(&format!("{n}/Verifier.sol"));
        let l = emit_fe(&vk).unwrap();
        // snarkjs: verifyProof(uint[2] _pA, uint[2][2] _pB, uint[2] _pC, uint[k] _pubSignals)
        assert!(sol.contains(&format!(
            "verifyProof(uint[2] calldata _pA, uint[2][2] calldata _pB, uint[2] calldata _pC, uint[{k}] calldata _pubSignals)"
        )));
        assert!(l.contains(&format!(
            "sol(\"verifyProof(uint256[2],uint256[2][2],uint256[2],uint256[{k}])\")"
        )));
    }
}

#[test]
fn snapshot_membership() {
    let (vk, fx) = load("membership");
    let e = emit_ingot(&vk, &opts("membership", Some(fx))).unwrap();
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/snapshots");
    for (file, got) in [
        ("membership_lib.fe", e.lib_fe.as_str()),
        ("membership_tests.fe", e.tests_fe.as_deref().unwrap()),
        ("membership_fe.toml", e.fe_toml.as_str()),
    ] {
        let p = dir.join(file);
        if std::env::var("UPDATE_SNAPSHOTS").is_ok() {
            std::fs::write(&p, got).unwrap();
        }
        let want = std::fs::read_to_string(&p).unwrap();
        assert_eq!(
            want, got,
            "{file} changed; rerun with UPDATE_SNAPSHOTS=1 if intended"
        );
    }
}

#[test]
fn refuses_invalid_keys() {
    let (good, fx) = load("multiplier");
    let o = opts("multiplier", Some(fx));
    // off curve alpha
    let mut vk = good.clone();
    vk.alpha_g1 = G1::new(1u8.into(), 3u8.into());
    assert!(emit_ingot(&vk, &o).is_err());
    // identity gamma / delta
    let mut vk = good.clone();
    vk.gamma_g2 = G2::identity();
    assert!(emit_ingot(&vk, &o).is_err());
    let mut vk = good.clone();
    vk.delta_g2 = G2::identity();
    assert!(emit_ingot(&vk, &o).is_err());
    // wrong IC count
    let mut vk = good.clone();
    vk.ic.pop();
    assert!(emit_fe(&vk).is_err());
    // non-canonical coordinate
    let mut vk = good.clone();
    vk.alpha_g1.x += num_bigint::BigUint::parse_bytes(
        b"21888242871839275222246405745257275088696311157297823662689037894645226208583",
        10,
    )
    .unwrap();
    assert!(emit_fe(&vk).is_err());
    // public input count that does not match the key
    let (_, mut fx2) = load("multiplier");
    fx2.public.push(1u8.into());
    assert!(emit_ingot(&good, &opts("multiplier", Some(fx2))).is_err());
    // bad names
    for bad in ["", "1x", "a-b", "a b"] {
        let mut o2 = o.clone();
        o2.name = bad.into();
        assert!(emit_ingot(&good, &o2).is_err(), "{bad}");
    }
}

